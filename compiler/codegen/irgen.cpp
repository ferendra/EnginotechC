std::string LLVMIRGenerator::generate(const Program& prog) {
    irStream_.str("");
    irStream_.clear();
    hasError_ = false;
    hasReturn_ = false;
    regCounter_ = 0;

    structs_.clear();
    fieldIndex_.clear();
    enums_.clear();
    functions_.clear();
    methods_.clear();
    methodOwner_.clear();
    sigs_.clear();
    stringConsts_.clear();
    pendingStrings_.clear();
    globals_.clear();
    slots_.clear();
    slotOrder_.clear();
    scopeStack_.clear();
    loopStack_.clear();
    curSelfType_.clear();

    irStream_ << "; Generated by EnginotechC++ M1\n";
    irStream_ << "; Target: x86_64\n\n";

    // Declaration pre-pass — MUST run before any emission: it registers
    // structs, enums, functions, methods and signatures. Losing this call
    // makes script-mode emit a duplicate @main (Fix #040).
    declareTopLevel(prog);

    // Runtime prelude (libc + string helpers)
    irStream_ << "declare i32 @printf(ptr, ...)\n";
    irStream_ << "declare i64 @strlen(ptr)\n";
    irStream_ << "declare ptr @malloc(i64)\n";
    irStream_ << "declare void @free(ptr)\n";
    irStream_ << "declare ptr @memcpy(ptr, ptr, i64)\n";
    irStream_ << "declare i32 @sprintf(ptr, ptr, ...)\n";
    irStream_ << "declare i32 @strcmp(ptr, ptr)\n";
    irStream_ << "declare ptr @strstr(ptr, ptr)\n";
    irStream_ << "declare void @abort()\n\n";

    irStream_ << "@.fmt.print = private unnamed_addr constant [4 x i8] c\"%s\\0A\\00\"\n";
    irStream_ << "@.fmt.int = private unnamed_addr constant [3 x i8] c\"%d\\00\"\n";
    irStream_ << "@.fmt.float = private unnamed_addr constant [5 x i8] c\"%.6f\\00\"\n";
    irStream_ << "@.bool.t = private unnamed_addr constant [5 x i8] c\"true\\00\"\n";
    irStream_ << "@.bool.f = private unnamed_addr constant [6 x i8] c\"false\\00\"\n\n";

    irStream_ << "define ptr @eng_str_concat(ptr %a, ptr %b) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %la = call i64 @strlen(ptr %a)\n";
    irStream_ << "  %lb = call i64 @strlen(ptr %b)\n";
    irStream_ << "  %tot = add i64 %la, %lb\n";
    irStream_ << "  %cap = add i64 %tot, 1\n";
    irStream_ << "  %buf = call ptr @malloc(i64 %cap)\n";
    irStream_ << "  call ptr @memcpy(ptr %buf, ptr %a, i64 %la)\n";
    irStream_ << "  %off = getelementptr i8, ptr %buf, i64 %la\n";
    irStream_ << "  %lb1 = add i64 %lb, 1\n";
    irStream_ << "  call ptr @memcpy(ptr %off, ptr %b, i64 %lb1)\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    irStream_ << "define ptr @eng_int_to_str(i32 %v) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 16)\n";
    irStream_ << "  call i32 (ptr, ptr, ...) @sprintf(ptr %buf, ptr @.fmt.int, i32 %v)\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    irStream_ << "define ptr @eng_float_to_str(double %v) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 64)\n";
    irStream_ << "  call i32 (ptr, ptr, ...) @sprintf(ptr %buf, ptr @.fmt.float, double %v)\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    irStream_ << "define ptr @eng_bool_to_str(i1 %v) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %r = select i1 %v, ptr @.bool.t, ptr @.bool.f\n";
    irStream_ << "  ret ptr %r\n";
    irStream_ << "}\n\n";

    // ---- Alpha builtins: conversion, math, string ops, input ----
    irStream_ << "declare i32 @atoi(ptr)\n";
    irStream_ << "declare double @atof(ptr)\n";
    irStream_ << "declare ptr @fgets(ptr, i32, ptr)\n";
    irStream_ << "declare i32 @toupper(i32)\n";
    irStream_ << "declare i32 @tolower(i32)\n";
    irStream_ << "declare double @sqrt(double)\n";
    irStream_ << "declare double @pow(double, double)\n";
    irStream_ << "declare double @floor(double)\n";
    irStream_ << "declare double @ceil(double)\n";
    irStream_ << "@stdin = external global ptr\n\n";

    // input(): read one line from stdin (newline stripped), malloc'd buffer
    irStream_ << "define ptr @eng_input() {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 4096)\n";
    irStream_ << "  %st = load ptr, ptr @stdin\n";
    irStream_ << "  %ok = call ptr @fgets(ptr %buf, i32 4096, ptr %st)\n";
    irStream_ << "  %isnull = icmp eq ptr %ok, null\n";
    irStream_ << "  br i1 %isnull, label %empty, label %strip\n";
    irStream_ << "empty:\n";
    irStream_ << "  store i8 0, ptr %buf\n";
    irStream_ << "  br label %done\n";
    irStream_ << "strip:\n";
    irStream_ << "  %len = call i64 @strlen(ptr %buf)\n";
    irStream_ << "  %haslen = icmp sgt i64 %len, 0\n";
    irStream_ << "  br i1 %haslen, label %checknl, label %done\n";
    irStream_ << "checknl:\n";
    irStream_ << "  %idx = sub i64 %len, 1\n";
    irStream_ << "  %last = getelementptr inbounds i8, ptr %buf, i64 %idx\n";
    irStream_ << "  %ch = load i8, ptr %last\n";
    irStream_ << "  %isnl = icmp eq i8 %ch, 10\n";
    irStream_ << "  br i1 %isnl, label %zap, label %done\n";
    irStream_ << "zap:\n";
    irStream_ << "  store i8 0, ptr %last\n";
    irStream_ << "  br label %done\n";
    irStream_ << "done:\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    // chr(i): single-char string from a byte value
    irStream_ << "define ptr @eng_chr(i32 %c) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 2)\n";
    irStream_ << "  %b = trunc i32 %c to i8\n";
    irStream_ << "  store i8 %b, ptr %buf\n";
    irStream_ << "  %nul = getelementptr inbounds i8, ptr %buf, i64 1\n";
    irStream_ << "  store i8 0, ptr %nul\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    // upper(s) / lower(s): fresh buffer, source untouched.
    // zext keeps byte values 0..255 so ctype calls stay well-defined.
    irStream_ << "define ptr @eng_case_map(ptr %s, i1 %up) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %len = call i64 @strlen(ptr %s)\n";
    irStream_ << "  %cap = add i64 %len, 1\n";
    irStream_ << "  %buf = call ptr @malloc(i64 %cap)\n";
    irStream_ << "  call ptr @memcpy(ptr %buf, ptr %s, i64 %cap)\n";
    irStream_ << "  br label %loop\n";
    irStream_ << "loop:\n";
    irStream_ << "  %i = phi i64 [ 0, %entry ], [ %next, %step ]\n";
    irStream_ << "  %cont = icmp ult i64 %i, %len\n";
    irStream_ << "  br i1 %cont, label %body, label %out\n";
    irStream_ << "body:\n";
    irStream_ << "  %p = getelementptr inbounds i8, ptr %buf, i64 %i\n";
    irStream_ << "  %ch8 = load i8, ptr %p\n";
    irStream_ << "  %ch = zext i8 %ch8 to i32\n";
    irStream_ << "  %upped = call i32 @toupper(i32 %ch)\n";
    irStream_ << "  %lowed = call i32 @tolower(i32 %ch)\n";
    irStream_ << "  %sel = select i1 %up, i32 %upped, i32 %lowed\n";
    irStream_ << "  %m8 = trunc i32 %sel to i8\n";
    irStream_ << "  store i8 %m8, ptr %p\n";
    irStream_ << "  br label %step\n";
    irStream_ << "step:\n";
    irStream_ << "  %next = add i64 %i, 1\n";
    irStream_ << "  br label %loop\n";
    irStream_ << "out:\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    // ---- Alpha builtins: file I/O, substring, repeat ----
    irStream_ << "declare ptr @fopen(ptr, ptr)\n";
    irStream_ << "declare i32 @fclose(ptr)\n";
    irStream_ << "declare i64 @fread(ptr, i64, i64, ptr)\n";
    irStream_ << "declare i64 @fwrite(ptr, i64, i64, ptr)\n";
    irStream_ << "declare i64 @fseek(ptr, i64, i32)\n";
    irStream_ << "declare i64 @ftell(ptr)\n";
    irStream_ << "declare void @rewind(ptr)\n";
    irStream_ << "declare i32 @remove(ptr)\n\n";

    irStream_ << "@.mode.r = private unnamed_addr constant [2 x i8] c\"r\\00\"\n";
    irStream_ << "@.mode.w = private unnamed_addr constant [2 x i8] c\"w\\00\"\n";
    irStream_ << "@.mode.a = private unnamed_addr constant [2 x i8] c\"a\\00\"\n";
    irStream_ << "@.empty.s = private unnamed_addr constant [1 x i8] zeroinitializer\n\n";

    // read_file(path): whole file as a string; "" when missing/unreadable
    irStream_ << "define ptr @eng_read_file(ptr %path) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %f = call ptr @fopen(ptr %path, ptr @.mode.r)\n";
    irStream_ << "  %bad = icmp eq ptr %f, null\n";
    irStream_ << "  br i1 %bad, label %fail, label %size\n";
    irStream_ << "size:\n";
    irStream_ << "  call i64 @fseek(ptr %f, i64 0, i32 2)\n";
    irStream_ << "  %sz = call i64 @ftell(ptr %f)\n";
    irStream_ << "  call void @rewind(ptr %f)\n";
    irStream_ << "  %cap = add i64 %sz, 1\n";
    irStream_ << "  %buf = call ptr @malloc(i64 %cap)\n";
    irStream_ << "  %rd = call i64 @fread(ptr %buf, i64 1, i64 %sz, ptr %f)\n";
    irStream_ << "  %nulp = getelementptr inbounds i8, ptr %buf, i64 %rd\n";
    irStream_ << "  store i8 0, ptr %nulp\n";
    irStream_ << "  call i32 @fclose(ptr %f)\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "fail:\n";
    irStream_ << "  ret ptr @.empty.s\n";
    irStream_ << "}\n\n";

    // write_file/append_file(path, data): true on success
    irStream_ << "define i1 @eng_write_file(ptr %path, ptr %data, i1 %ap) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %mode = select i1 %ap, ptr @.mode.a, ptr @.mode.w\n";
    irStream_ << "  %f = call ptr @fopen(ptr %path, ptr %mode)\n";
    irStream_ << "  %bad = icmp eq ptr %f, null\n";
    irStream_ << "  br i1 %bad, label %fail, label %go\n";
    irStream_ << "go:\n";
    irStream_ << "  %len = call i64 @strlen(ptr %data)\n";
    irStream_ << "  %wr = call i64 @fwrite(ptr %data, i64 1, i64 %len, ptr %f)\n";
    irStream_ << "  call i32 @fclose(ptr %f)\n";
    irStream_ << "  %same = icmp eq i64 %wr, %len\n";
    irStream_ << "  ret i1 %same\n";
    irStream_ << "fail:\n";
    irStream_ << "  ret i1 false\n";
    irStream_ << "}\n\n";

    // file_exists(path)
    irStream_ << "define i1 @eng_file_exists(ptr %path) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %f = call ptr @fopen(ptr %path, ptr @.mode.r)\n";
    irStream_ << "  %bad = icmp eq ptr %f, null\n";
    irStream_ << "  br i1 %bad, label %no, label %yes\n";
    irStream_ << "yes:\n";
    irStream_ << "  call i32 @fclose(ptr %f)\n";
    irStream_ << "  ret i1 true\n";
    irStream_ << "no:\n";
    irStream_ << "  ret i1 false\n";
    irStream_ << "}\n\n";

    // substring(s, start, len): clamped to the string bounds
    irStream_ << "define ptr @eng_substr(ptr %s, i64 %start, i64 %len) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %slen = call i64 @strlen(ptr %s)\n";
    irStream_ << "  %neg0 = icmp slt i64 %start, 0\n";
    irStream_ << "  %s0 = select i1 %neg0, i64 0, i64 %start\n";
    irStream_ << "  %past = icmp sgt i64 %s0, %slen\n";
    irStream_ << "  %s1 = select i1 %past, i64 %slen, i64 %s0\n";
    irStream_ << "  %avail = sub i64 %slen, %s1\n";
    irStream_ << "  %neg1 = icmp slt i64 %len, 0\n";
    irStream_ << "  %l0 = select i1 %neg1, i64 0, i64 %len\n";
    irStream_ << "  %over = icmp sgt i64 %l0, %avail\n";
    irStream_ << "  %take = select i1 %over, i64 %avail, i64 %l0\n";
    irStream_ << "  %cap = add i64 %take, 1\n";
    irStream_ << "  %buf = call ptr @malloc(i64 %cap)\n";
    irStream_ << "  %src = getelementptr inbounds i8, ptr %s, i64 %s1\n";
    irStream_ << "  call ptr @memcpy(ptr %buf, ptr %src, i64 %take)\n";
    irStream_ << "  %nulp = getelementptr inbounds i8, ptr %buf, i64 %take\n";
    irStream_ << "  store i8 0, ptr %nulp\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    // repeat(s, n): n copies concatenated; negative n yields ""
    irStream_ << "define ptr @eng_repeat(ptr %s, i64 %n) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %len = call i64 @strlen(ptr %s)\n";
    irStream_ << "  %neg = icmp slt i64 %n, 0\n";
    irStream_ << "  %cnt = select i1 %neg, i64 0, i64 %n\n";
    irStream_ << "  %tot = mul i64 %len, %cnt\n";
    irStream_ << "  %cap = add i64 %tot, 1\n";
    irStream_ << "  %buf = call ptr @malloc(i64 %cap)\n";
    irStream_ << "  br label %loop\n";
    irStream_ << "loop:\n";
    irStream_ << "  %i = phi i64 [ 0, %entry ], [ %nx, %body ]\n";
    irStream_ << "  %cont = icmp ult i64 %i, %cnt\n";
    irStream_ << "  br i1 %cont, label %body, label %out\n";
    irStream_ << "body:\n";
    irStream_ << "  %off = mul i64 %i, %len\n";
    irStream_ << "  %dst = getelementptr inbounds i8, ptr %buf, i64 %off\n";
    irStream_ << "  call ptr @memcpy(ptr %dst, ptr %s, i64 %len)\n";
    irStream_ << "  %nx = add i64 %i, 1\n";
    irStream_ << "  br label %loop\n";
    irStream_ << "out:\n";
    irStream_ << "  %nulp = getelementptr inbounds i8, ptr %buf, i64 %tot\n";
    irStream_ << "  store i8 0, ptr %nulp\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    // ---- OS builtins: shell commands, output capture, app launching ----
    irStream_ << "declare i32 @system(ptr)\n";
    irStream_ << "declare ptr @popen(ptr, ptr)\n";
    irStream_ << "declare i32 @pclose(ptr)\n";
    irStream_ << "declare i32 @snprintf(ptr, i64, ptr, ...)\n\n";

#ifdef _WIN32
    // Windows: _system() already returns the plain exit code
    irStream_ << "define i32 @eng_run_command(ptr %cmd) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %r = call i32 @system(ptr %cmd)\n";
    irStream_ << "  ret i32 %r\n";
    irStream_ << "}\n\n";
#else
    // POSIX: system() returns an encoded status; bits 8..15 hold the exit code
    irStream_ << "define i32 @eng_run_command(ptr %cmd) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %st = call i32 @system(ptr %cmd)\n";
    irStream_ << "  %r = ashr i32 %st, 8\n";
    irStream_ << "  ret i32 %r\n";
    irStream_ << "}\n\n";
#endif

    // exec_output(cmd): run a command, return everything it prints to stdout
    irStream_ << "define ptr @eng_exec_output(ptr %cmd) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %f = call ptr @popen(ptr %cmd, ptr @.mode.r)\n";
    irStream_ << "  %bad = icmp eq ptr %f, null\n";
    irStream_ << "  br i1 %bad, label %fail, label %go\n";
    irStream_ << "go:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 65537)\n";
    irStream_ << "  br label %loop\n";
    irStream_ << "loop:\n";
    irStream_ << "  %off = phi i64 [ 0, %go ], [ %newoff, %more ]\n";
    irStream_ << "  %left = sub i64 65536, %off\n";
    irStream_ << "  %left32 = trunc i64 %left to i32\n";
    irStream_ << "  %roomy = icmp sgt i32 %left32, 1\n";
    irStream_ << "  %sz = select i1 %roomy, i32 %left32, i32 1\n";
    irStream_ << "  %dst = getelementptr inbounds i8, ptr %buf, i64 %off\n";
    irStream_ << "  %got = call ptr @fgets(ptr %dst, i32 %sz, ptr %f)\n";
    irStream_ << "  %isnull = icmp eq ptr %got, null\n";
    irStream_ << "  br i1 %isnull, label %finish, label %counted\n";
    irStream_ << "counted:\n";
    irStream_ << "  %rd = call i64 @strlen(ptr %dst)\n";
    irStream_ << "  %newoff = add i64 %off, %rd\n";
    irStream_ << "  %full = icmp ugt i64 %newoff, 65535\n";
    irStream_ << "  br i1 %full, label %finish, label %more\n";
    irStream_ << "more:\n";
    irStream_ << "  br label %loop\n";
    irStream_ << "finish:\n";
    irStream_ << "  %endp = getelementptr inbounds i8, ptr %buf, i64 %off\n";
    irStream_ << "  store i8 0, ptr %endp\n";
    irStream_ << "  %rc = call i32 @pclose(ptr %f)\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "fail:\n";
    irStream_ << "  ret ptr @.empty.s\n";
    irStream_ << "}\n\n";

#ifdef _WIN32
    // open_app(app): cmd.exe start — quotes rejected to keep quoting intact
    irStream_ << "@.fmt.winstart = private unnamed_addr constant [14 x i8] c\"start \\22\\22 \\22%s\\22\\00\"\n\n";
    irStream_ << "define i1 @eng_open_app(ptr %app) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  br label %scan\n";
    irStream_ << "scan:\n";
    irStream_ << "  %i = phi i64 [ 0, %entry ], [ %ni, %adv ]\n";
    irStream_ << "  %p = getelementptr inbounds i8, ptr %app, i64 %i\n";
    irStream_ << "  %c = load i8, ptr %p\n";
    irStream_ << "  %isq = icmp eq i8 %c, 34\n";
    irStream_ << "  br i1 %isq, label %bad, label %chkend\n";
    irStream_ << "chkend:\n";
    irStream_ << "  %done = icmp eq i8 %c, 0\n";
    irStream_ << "  br i1 %done, label %build, label %adv\n";
    irStream_ << "adv:\n";
    irStream_ << "  %ni = add i64 %i, 1\n";
    irStream_ << "  br label %scan\n";
    irStream_ << "build:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 8192)\n";
    irStream_ << "  call i32 (ptr, i64, ptr, ...) @snprintf(ptr %buf, i64 8192, ptr @.fmt.winstart, ptr %app)\n";
    irStream_ << "  %r = call i32 @system(ptr %buf)\n";
    irStream_ << "  %ok = icmp eq i32 %r, 0\n";
    irStream_ << "  ret i1 %ok\n";
    irStream_ << "bad:\n";
    irStream_ << "  ret i1 false\n";
    irStream_ << "}\n\n";
#elif defined(__APPLE__)
    // macOS: open handles apps, files and URLs alike
    irStream_ << "@.fmt.macopen = private unnamed_addr constant [26 x i8] c\"open '%s' >/dev/null 2>&1\\00\"\n\n";
    irStream_ << "define i1 @eng_open_app(ptr %app) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 8192)\n";
    irStream_ << "  call i32 (ptr, i64, ptr, ...) @snprintf(ptr %buf, i64 8192, ptr @.fmt.macopen, ptr %app)\n";
    irStream_ << "  %r = call i32 @system(ptr %buf)\n";
    irStream_ << "  %ok = icmp eq i32 %r, 0\n";
    irStream_ << "  ret i1 %ok\n";
    irStream_ << "}\n\n";
#else
    // Linux/BSD: single-quote wrap neutralizes shell metacharacters, so the
    // only hazardous byte is ' itself — reject it before touching the shell.
    // 1) command -v finds real executables -> spawn detached (nohup … &)
    // 2) otherwise xdg-open covers files and URLs
    irStream_ << "@.fmt.appcheck = private unnamed_addr constant [32 x i8] c\"command -v '%s' >/dev/null 2>&1\\00\"\n";
    irStream_ << "@.fmt.applaunch = private unnamed_addr constant [29 x i8] c\"nohup '%s' >/dev/null 2>&1 &\\00\"\n";
    irStream_ << "@.fmt.xdgopen = private unnamed_addr constant [30 x i8] c\"xdg-open '%s' >/dev/null 2>&1\\00\"\n\n";
    irStream_ << "define i1 @eng_open_app(ptr %app) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  br label %scan\n";
    irStream_ << "scan:\n";
    irStream_ << "  %i = phi i64 [ 0, %entry ], [ %ni, %adv ]\n";
    irStream_ << "  %p = getelementptr inbounds i8, ptr %app, i64 %i\n";
    irStream_ << "  %c = load i8, ptr %p\n";
    irStream_ << "  %isq = icmp eq i8 %c, 39\n";
    irStream_ << "  br i1 %isq, label %bad, label %chkend\n";
    irStream_ << "chkend:\n";
    irStream_ << "  %done = icmp eq i8 %c, 0\n";
    irStream_ << "  br i1 %done, label %build, label %adv\n";
    irStream_ << "adv:\n";
    irStream_ << "  %ni = add i64 %i, 1\n";
    irStream_ << "  br label %scan\n";
    irStream_ << "build:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 8192)\n";
    irStream_ << "  call i32 (ptr, i64, ptr, ...) @snprintf(ptr %buf, i64 8192, ptr @.fmt.appcheck, ptr %app)\n";
    irStream_ << "  %rc = call i32 @system(ptr %buf)\n";
    irStream_ << "  %found = icmp eq i32 %rc, 0\n";
    irStream_ << "  br i1 %found, label %spawn, label %tryopen\n";
    irStream_ << "spawn:\n";
    irStream_ << "  %lbuf = call ptr @malloc(i64 8192)\n";
    irStream_ << "  call i32 (ptr, i64, ptr, ...) @snprintf(ptr %lbuf, i64 8192, ptr @.fmt.applaunch, ptr %app)\n";
    irStream_ << "  call i32 @system(ptr %lbuf)\n";
    irStream_ << "  ret i1 true\n";
    irStream_ << "tryopen:\n";
    irStream_ << "  %obuf = call ptr @malloc(i64 8192)\n";
    irStream_ << "  call i32 (ptr, i64, ptr, ...) @snprintf(ptr %obuf, i64 8192, ptr @.fmt.xdgopen, ptr %app)\n";
    irStream_ << "  %r2 = call i32 @system(ptr %obuf)\n";
    irStream_ << "  %ok = icmp eq i32 %r2, 0\n";
    irStream_ << "  ret i1 %ok\n";
    irStream_ << "bad:\n";
    irStream_ << "  ret i1 false\n";
    irStream_ << "}\n\n";

    // ---- hardware chat: serial port (POSIX termios) ----
    irStream_ << "declare i32 @open(ptr, i32, ...)\n";
    irStream_ << "declare i64 @read(i32, ptr, i64)\n";
    irStream_ << "declare i64 @write(i32, ptr, i64)\n";
    irStream_ << "declare i32 @close(i32)\n";
    irStream_ << "declare i32 @tcgetattr(i32, ptr)\n";
    irStream_ << "declare i32 @tcsetattr(i32, i32, ptr)\n";
    irStream_ << "declare void @cfmakeraw(ptr)\n";
    irStream_ << "declare i32 @cfsetispeed(ptr, i32)\n";
    irStream_ << "declare i32 @cfsetospeed(ptr, i32)\n\n";
    irStream_ << "@eng_serial_fd = global i32 -1\n";
    irStream_ << "@eng_serial_tio = global [60 x i8] zeroinitializer\n\n";
    // baud number -> Linux speed code (asm-generic termbits); unknown -> B9600
    irStream_ << "define internal i32 @eng_baud_code(i32 %b) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %s115200 = icmp eq i32 %b, 115200\n";
    irStream_ << "  %v0 = select i1 %s115200, i32 4098, i32 12\n";
    irStream_ << "  %s57600 = icmp eq i32 %b, 57600\n";
    irStream_ << "  %v1 = select i1 %s57600, i32 4097, i32 %v0\n";
    irStream_ << "  %s38400 = icmp eq i32 %b, 38400\n";
    irStream_ << "  %v2 = select i1 %s38400, i32 14, i32 %v1\n";
    irStream_ << "  %s19200 = icmp eq i32 %b, 19200\n";
    irStream_ << "  %v3 = select i1 %s19200, i32 13, i32 %v2\n";
    irStream_ << "  %s4800 = icmp eq i32 %b, 4800\n";
    irStream_ << "  %v4 = select i1 %s4800, i32 11, i32 %v3\n";
    irStream_ << "  %s2400 = icmp eq i32 %b, 2400\n";
    irStream_ << "  %v5 = select i1 %s2400, i32 10, i32 %v4\n";
    irStream_ << "  %s1200 = icmp eq i32 %b, 1200\n";
    irStream_ << "  %v6 = select i1 %s1200, i32 9, i32 %v5\n";
    irStream_ << "  ret i32 %v6\n";
    irStream_ << "}\n\n";

    // serial_open(port, baud): raw mode, 8N1, VMIN=0/VTIME=1 (read waits <=0.1s)
    irStream_ << "define i1 @eng_serial_open(ptr %port, i32 %baud) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %old = load i32, ptr @eng_serial_fd\n";
    irStream_ << "  %hadold = icmp sge i32 %old, 0\n";
    irStream_ << "  br i1 %hadold, label %closeold, label %doopen\n";
    irStream_ << "closeold:\n";
    irStream_ << "  %dc = call i32 @close(i32 %old)\n";
    irStream_ << "  br label %doopen\n";
    irStream_ << "doopen:\n";
    // O_RDWR | O_NOCTTY = 258 — fd harus blocking agar VTIME (100 ms) berlaku;
    // dengan O_NONBLOCK read() langsung EAGAIN dan timeout VTIME diabaikan.
    irStream_ << "  %fd = call i32 (ptr, i32, ...) @open(ptr %port, i32 258, i32 0)\n";
    irStream_ << "  store i32 %fd, ptr @eng_serial_fd\n";
    irStream_ << "  %bad = icmp slt i32 %fd, 0\n";
    irStream_ << "  br i1 %bad, label %fail, label %cfg\n";
    irStream_ << "cfg:\n";
    irStream_ << "  %gs = call i32 @tcgetattr(i32 %fd, ptr @eng_serial_tio)\n";
    irStream_ << "  call void @cfmakeraw(ptr @eng_serial_tio)\n";
    irStream_ << "  %code = call i32 @eng_baud_code(i32 %baud)\n";
    irStream_ << "  %si = call i32 @cfsetispeed(ptr @eng_serial_tio, i32 %code)\n";
    irStream_ << "  %so = call i32 @cfsetospeed(ptr @eng_serial_tio, i32 %code)\n";
    // struct termios (Linux): c_cflag@8 u32, c_cc[5]=VTIME@22, c_cc[6]=VMIN@23
    irStream_ << "  %vtp = getelementptr inbounds [60 x i8], ptr @eng_serial_tio, i64 0, i64 22\n";
    irStream_ << "  store i8 1, ptr %vtp\n";
    irStream_ << "  %vmp = getelementptr inbounds [60 x i8], ptr @eng_serial_tio, i64 0, i64 23\n";
    irStream_ << "  store i8 0, ptr %vmp\n";
    // c_cflag |= CREAD (128) | CLOCAL (2048)
    irStream_ << "  %cfp = getelementptr inbounds [60 x i8], ptr @eng_serial_tio, i64 0, i64 8\n";
    irStream_ << "  %cf = load i32, ptr %cfp\n";
    irStream_ << "  %cfn = or i32 %cf, 2176\n";
    irStream_ << "  store i32 %cfn, ptr %cfp\n";
    irStream_ << "  %ss = call i32 @tcsetattr(i32 %fd, i32 0, ptr @eng_serial_tio)\n";
    irStream_ << "  %ok = icmp eq i32 %ss, 0\n";
    irStream_ << "  ret i1 %ok\n";
    irStream_ << "fail:\n";
    irStream_ << "  ret i1 false\n";
    irStream_ << "}\n\n";

    // serial_write(data): true when every byte reached the wire
    irStream_ << "define i1 @eng_serial_write(ptr %data) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %fd = load i32, ptr @eng_serial_fd\n";
    irStream_ << "  %ready = icmp sge i32 %fd, 0\n";
    irStream_ << "  br i1 %ready, label %go, label %fail\n";
    irStream_ << "go:\n";
    irStream_ << "  %len = call i64 @strlen(ptr %data)\n";
    irStream_ << "  %w = call i64 @write(i32 %fd, ptr %data, i64 %len)\n";
    irStream_ << "  %same = icmp eq i64 %w, %len\n";
    irStream_ << "  ret i1 %same\n";
    irStream_ << "fail:\n";
    irStream_ << "  ret i1 false\n";
    irStream_ << "}\n\n";

    // serial_read_line(): read up to '\n' (stripped); gives up after ~5s idle
    irStream_ << "define ptr @eng_serial_read_line() {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 4096)\n";
    irStream_ << "  %ip = alloca i64\n";
    irStream_ << "  %pp = alloca i32\n";
    irStream_ << "  store i64 0, ptr %ip\n";
    irStream_ << "  store i32 0, ptr %pp\n";
    irStream_ << "  %fd = load i32, ptr @eng_serial_fd\n";
    irStream_ << "  %ready = icmp sge i32 %fd, 0\n";
    irStream_ << "  br i1 %ready, label %loop, label %closed\n";
    irStream_ << "closed:\n";
    irStream_ << "  store i8 0, ptr %buf\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "loop:\n";
    irStream_ << "  %i = load i64, ptr %ip\n";
    irStream_ << "  %full = icmp ugt i64 %i, 4094\n";
    irStream_ << "  br i1 %full, label %fin, label %rd\n";
    irStream_ << "rd:\n";
    irStream_ << "  %dst = getelementptr inbounds i8, ptr %buf, i64 %i\n";
    irStream_ << "  %r = call i64 @read(i32 %fd, ptr %dst, i64 1)\n";
    irStream_ << "  %got = icmp eq i64 %r, 1\n";
    irStream_ << "  br i1 %got, label %chkit, label %missed\n";
    irStream_ << "chkit:\n";
    irStream_ << "  %ch = load i8, ptr %dst\n";
    irStream_ << "  %isnl = icmp eq i8 %ch, 10\n";
    irStream_ << "  br i1 %isnl, label %fin, label %keep\n";
    irStream_ << "keep:\n";
    irStream_ << "  %nx = add i64 %i, 1\n";
    irStream_ << "  store i64 %nx, ptr %ip\n";
    irStream_ << "  store i32 0, ptr %pp\n";
    irStream_ << "  br label %loop\n";
    irStream_ << "missed:\n";
    irStream_ << "  %np = load i32, ptr %pp\n";
    irStream_ << "  %np1 = add i32 %np, 1\n";
    irStream_ << "  store i32 %np1, ptr %pp\n";
    irStream_ << "  %tired = icmp sgt i32 %np1, 50\n";
    irStream_ << "  br i1 %tired, label %fin, label %loop\n";
    irStream_ << "fin:\n";
    irStream_ << "  %ie = load i64, ptr %ip\n";
    irStream_ << "  %endp = getelementptr inbounds i8, ptr %buf, i64 %ie\n";
    irStream_ << "  store i8 0, ptr %endp\n";
    irStream_ << "  ret ptr %buf\n";
    irStream_ << "}\n\n";

    // serial_close(): release the port
    irStream_ << "define i32 @eng_serial_close() {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %fd = load i32, ptr @eng_serial_fd\n";
    irStream_ << "  %ready = icmp sge i32 %fd, 0\n";
    irStream_ << "  br i1 %ready, label %go, label %done\n";
    irStream_ << "go:\n";
    irStream_ << "  %d = call i32 @close(i32 %fd)\n";
    irStream_ << "  store i32 -1, ptr @eng_serial_fd\n";
    irStream_ << "  br label %done\n";
    irStream_ << "done:\n";
    irStream_ << "  ret i32 0\n";
    irStream_ << "}\n\n";
#endif

    // ---- Additional OS helpers for hardware workflow ----

    // sleep(ms): pause execution for milliseconds (cross-platform)
#ifdef _WIN32
    irStream_ << "declare void @Sleep(i32)\n\n";
    irStream_ << "define void @eng_sleep(i32 %ms) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  call void @Sleep(i32 %ms)\n";
    irStream_ << "  ret void\n";
    irStream_ << "}\n\n";
#else
    irStream_ << "declare i32 @usleep(i32)\n\n";
    irStream_ << "define void @eng_sleep(i32 %ms) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %us = mul i32 %ms, 1000\n";
    irStream_ << "  call i32 @usleep(i32 %us)\n";
    irStream_ << "  ret void\n";
    irStream_ << "}\n\n";
#endif

    // env_get(name) -> string: lookup environment variable
    irStream_ << "declare ptr @getenv(ptr)\n\n";
    irStream_ << "define ptr @eng_env_get(ptr %name) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %val = call ptr @getenv(ptr %name)\n";
    irStream_ << "  %isnull = icmp eq ptr %val, null\n";
    irStream_ << "  %result = select i1 %isnull, ptr @.empty.s, ptr %val\n";
    irStream_ << "  ret ptr %result\n";
    irStream_ << "}\n\n";

    // cwd() -> string: current working directory
    irStream_ << "declare ptr @getcwd(ptr, i64)\n\n";
    irStream_ << "define ptr @eng_cwd() {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %buf = call ptr @malloc(i64 4096)\n";
    irStream_ << "  %result = call ptr @getcwd(ptr %buf, i64 4096)\n";
    irStream_ << "  %isnull = icmp eq ptr %result, null\n";
    irStream_ << "  %safe = select i1 %isnull, ptr @.empty.s, ptr %buf\n";
    irStream_ << "  ret ptr %safe\n";
    irStream_ << "}\n\n";

    // path_join(base, relative) -> string: combine paths (POSIX style)
    irStream_ << "define ptr @eng_path_join(ptr %base, ptr %rel) {\n";
    irStream_ << "entry:\n";
    irStream_ << "  %blen = call i64 @strlen(ptr %base)\n";
    irStream_ << "  %rlen = call i64 @strlen(ptr %rel)\n";
    irStream_ << "  %sep = getelementptr inbounds i8, ptr %base, i64 %blen\n";
    irStream_ << "  %last = load i8, ptr %sep\n";
    irStream_ << "  %need_sep = icmp ne i8 %last, 47\n";  ; // 47 = '/'
    irStream_ << "  %cap1 = add i64 %blen, %rlen\n";
    irStream_ << "  %cap = add i64 %cap1, 2\n";
    irStream_ << "  %dst = call ptr @malloc(i64 %cap)\n";
    irStream_ << "  call ptr @memcpy(ptr %dst, ptr %base, i64 %blen)\n";
    irStream_ << "  %off1 = add i64 %blen, 1\n";
    irStream_ << "  %sep_char = select i1 %need_sep, i8 47, i8 0\n";
    irStream_ << "  %sep_ptr = getelementptr inbounds i8, ptr %dst, i64 %blen\n";
    irStream_ << "  store i8 %sep_char, ptr %sep_ptr\n";
    irStream_ << "  %src = getelementptr inbounds i8, ptr %rel, i64 0\n";
    irStream_ << "  %skip = add i64 %blen, %off1\n";
    irStream_ << "  %dst2 = getelementptr inbounds i8, ptr %dst, i64 %skip\n";
    irStream_ << "  call ptr @memcpy(ptr %dst2, ptr %src, i64 %rlen)\n";
    irStream_ << "  %final = add i64 %skip, %rlen\n";
    irStream_ << "  %nul = getelementptr inbounds i8, ptr %dst, i64 %final\n";
    irStream_ << "  store i8 0, ptr %nul\n";
    irStream_ << "  ret ptr %dst\n";
    irStream_ << "}\n\n";

    // Emit string globals collected from the whole program
    std::vector<std::string> allStrings;
    collectStrings(prog.topLevel, allStrings);
    // Seed constants used by builtins so they are never "late"
    allStrings.push_back("");
    allStrings.push_back(" ");
    for (const auto& s : allStrings) {
        if (stringConsts_.count(s)) continue;
        std::string gvName = "@.str." + std::to_string(stringConsts_.size());
        stringConsts_[s] = {gvName, static_cast<int>(s.size())};
    }
    for (const auto& [content, meta] : stringConsts_) {
        irStream_ << meta.first << " = private unnamed_addr constant ["
                  << (content.size() + 1) << " x i8] c\"" << escapeLLVMString(content)
                  << "\\00\"\n";
    }
    if (!stringConsts_.empty()) irStream_ << "\n";

    // Struct types first (functions may reference them)
    for (const auto& item : prog.topLevel) {
        if (item && item->kind() == StmtKind::StructDecl)
            emitStructType(static_cast<StructDecl*>(item.get()));
    }
    if (!structs_.empty()) irStream_ << "\n";

    for (const auto& item : prog.topLevel) {
        if (item && item->kind() == StmtKind::EnumDecl)
            emitEnumConstants(static_cast<EnumDecl*>(item.get()));
    }

    // Free functions
    for (const auto& item : prog.topLevel) {
        if (item && item->kind() == StmtKind::FunctionDecl)
            emitFunction(static_cast<FunctionDecl*>(item.get()));
    }

    // Methods
    for (const auto& item : prog.topLevel) {
        if (item && item->kind() == StmtKind::Impl)
            emitImpl(static_cast<ImplDecl*>(item.get()));
    }

    // Ensure main exists — Python-style script mode:
    // top-level statements become the body of an implicit main().
    if (!functions_.count("main")) {
        std::vector<StmtPtr> scriptStmts;
        for (const auto& item : prog.topLevel) {
            if (!item) continue;
            switch (item->kind()) {
                case StmtKind::FunctionDecl: case StmtKind::StructDecl:
                case StmtKind::EnumDecl: case StmtKind::Impl:
                case StmtKind::Interface: case StmtKind::Import:
                    break; // declarations are emitted separately
                default:
                    scriptStmts.push_back(item);
            }
        }
        if (!scriptStmts.empty()) {
            auto retTy = std::make_shared<BasicType>("int");
            FunctionDecl scriptMain("main", retTy, {}, scriptStmts, 0, 0);
            scriptMain.isMain = true;
            scriptMode_ = true;
            emitFunction(&scriptMain);
            scriptMode_ = false;
        } else {
            irStream_ << "; Default main\n";
            irStream_ << "define i32 @main() {\nentry:\n  ret i32 0\n}\n";
        }
    }

    // Flush late string constants (registered during body emission)
    if (!pendingStrings_.empty()) {
        irStream_ << "\n; late string constants\n";
        for (const auto& content : pendingStrings_) {
            const auto& meta = stringConsts_[content];
            irStream_ << meta.first << " = private unnamed_addr constant ["
                      << (content.size() + 1) << " x i8] c\""
                      << escapeLLVMString(content) << "\\00\"\n";
        }
        pendingStrings_.clear();
    }

    return irStream_.str();
}

// ---- declaration pre-pass ----

void LLVMIRGenerator::declareTopLevel(const Program& prog) {
    for (const auto& item : prog.topLevel) {
        if (!item) continue;
        switch (item->kind()) {
            case StmtKind::StructDecl:
                registerStruct(static_cast<StructDecl*>(item.get()));
                break;
            case StmtKind::EnumDecl:
                registerEnum(static_cast<EnumDecl*>(item.get()));
                break;
            case StmtKind::FunctionDecl:
                registerFunction(static_cast<FunctionDecl*>(item.get()));
                break;
            case StmtKind::Impl: {
                auto* im = static_cast<ImplDecl*>(item.get());
                curSelfType_ = im->structName;
                for (const auto& m : im->methods) {
                    if (m && m->kind() == StmtKind::FunctionDecl)
                        registerFunction(static_cast<FunctionDecl*>(m.get()));
                }
                curSelfType_.clear();
                break;
            }
            default:
                break;
        }
    }
}

void LLVMIRGenerator::registerStruct(const StructDecl* st) {
    int idx = 0;
    for (const auto& [fname, ftype] : st->fields) {
        fieldIndex_[st->name + "." + fname] = idx++;
    }
    structs_[st->name] = st->fields;
}

void LLVMIRGenerator::registerEnum(const EnumDecl* en) {
    std::vector<std::string> variants;
    variants.reserve(en->variants.size());
    for (const auto& [vname, payload] : en->variants) {
        (void)payload;
        variants.push_back(vname);
    }
    enums_[en->name] = variants;
}

void LLVMIRGenerator::registerFunction(const FunctionDecl* fn) {
    const bool method = !curSelfType_.empty();
    FnSig sig;
    sig.ret = getTypeStr(fn->returnType);
    for (const auto& [pname, ptype] : fn->params) {
        (void)pname;
        sig.params.push_back(getTypeStr(ptype));
    }
    const std::string key = method ? curSelfType_ + "." + fn->name : fn->name;
    sigs_[key] = sig;
    if (method) {
        methods_[key] = fn;
        if (!methodOwner_.count(fn->name)) methodOwner_[fn->name] = curSelfType_;
    } else {
        functions_[fn->name] = fn;
    }
}

// ---- emission ----

void LLVMIRGenerator::emitStructType(const StructDecl* st) {
    irStream_ << llvmTypeName(st->name) << " = type { ";
    bool first = true;
    for (const auto& [fname, ftype] : st->fields) {
        (void)fname;
        if (!first) irStream_ << ", ";
        irStream_ << getLLVMType(ftype ? ftype->getName() : "int");
        first = false;
    }
    irStream_ << " }\n";
}

void LLVMIRGenerator::emitEnumConstants(const EnumDecl* en) {
    irStream_ << "; enum " << en->name << ": ";
    for (size_t i = 0; i < en->variants.size(); ++i) {
        if (i) irStream_ << ", ";
        irStream_ << en->variants[i].first << "=" << i;
    }
    irStream_ << "\n";
}

void LLVMIRGenerator::emitImpl(const ImplDecl* im) {
    curSelfType_ = im->structName;
    for (const auto& m : im->methods) {
        if (m && m->kind() == StmtKind::FunctionDecl)
            emitFunction(static_cast<FunctionDecl*>(m.get()));
    }
    curSelfType_.clear();
}

void LLVMIRGenerator::emitFunction(const FunctionDecl* fn) {
    const bool method = !curSelfType_.empty();
    const std::string key = method ? curSelfType_ + "." + fn->name : fn->name;

    FnSig sig;
    auto sit = sigs_.find(key);
    if (sit != sigs_.end()) {
        sig = sit->second;
    } else {
        sig.ret = getTypeStr(fn->returnType);
        for (const auto& [pn, pt] : fn->params) {
            (void)pn;
            sig.params.push_back(getTypeStr(pt));
        }
    }

    curRetTy_ = sig.ret.empty() ? "i32" : sig.ret;
    curRetVT_ = fn->returnType ? vtOfType(fn->returnType) :
                                 (curRetTy_ == "void" ? VT::Void : VT::Int);
    hasReturn_ = false;

    slots_.clear();
    slotOrder_.clear();
    scopeStack_.clear();
    loopStack_.clear();
    pushScope();

    const std::string symbol =
        method ? sanitize(curSelfType_) + "_" + fn->name : sanitize(fn->name);

    irStream_ << "define " << curRetTy_ << " @" << symbol << "(";
    bool first = true;
    for (const auto& [pname, ptype] : fn->params) {
        if (!first) irStream_ << ", ";
        irStream_ << getLLVMType(ptype ? ptype->getName() : "int") << " %" << pname;
        first = false;
    }
    irStream_ << ") {\nentry:\n";

    // Parameter slots
    for (const auto& [pname, ptype] : fn->params) {
        declareSlot(pname, ptype);
    }

    // Make top-level globals visible (locals/params shadow them naturally)
    injectGlobalSlots();

    // Hoist all local declarations into entry allocas
    prescanVars(fn->body);
    emitEntryAllocas();

    // Store incoming parameter values into their slots
    for (const auto& [pname, ptype] : fn->params) {
        (void)ptype;
        auto it = slots_.find(pname);
        if (it == slots_.end()) continue;
        irStream_ << "  store " << it->second.llvmTy << " %" << pname
                  << ", ptr " << it->second.reg << "\n";
    }

    // Program entry point: run global initializers first.
    // In script mode the implicit main's body already executes every
    // top-level let in source order — initializing twice would evaluate
    // initializers before earlier body statements ran.
    if (!method && fn->name == "main" && !scriptMode_) {
        emitGlobalInits();
    }

    for (const auto& stmt : fn->body) {
        if (!stmt) break;
        emitStmt(stmt);
    }

    if (!hasReturn_) {
        if (curRetTy_ == "void") {
            irStream_ << "  ret void\n";
        } else if (curRetTy_ == "double") {
            irStream_ << "  ret double 0.0\n";
        } else if (curRetTy_ == "i1") {
            irStream_ << "  ret i1 false\n";
        } else if (curRetTy_ == "ptr") {
            irStream_ << "  ret ptr null\n";
        } else {
            irStream_ << "  ret " << curRetTy_ << " 0\n";
        }
    }

    irStream_ << "}\n\n";
    popScope();
}

void LLVMIRGenerator::prescanVars(const std::vector<StmtPtr>& body) {
    for (const auto& stmt : body) prescanStmt(stmt);
}

void LLVMIRGenerator::prescanStmt(const StmtPtr& stmt) {
    if (!stmt) return;
    switch (stmt->kind()) {
        case StmtKind::Let: {
            auto* s = static_cast<LetStmt*>(stmt.get());
            declareSlot(s->name,
                        s->type ? s->type : inferTypeOf(s->init.get()));
            break;
        }
        case StmtKind::Mut: {
            auto* s = static_cast<MutStmt*>(stmt.get());
            declareSlot(s->name,
                        s->type ? s->type : inferTypeOf(s->init.get()));
            break;
        }
        case StmtKind::Const: {
            auto* s = static_cast<ConstStmt*>(stmt.get());
            declareSlot(s->name, inferTypeOf(s->init.get()));
            break;
        }
        case StmtKind::Block:
            prescanVars(static_cast<BlockStmt*>(stmt.get())->body);
            break;
        case StmtKind::If: {
            auto* s = static_cast<IfStmt*>(stmt.get());
            prescanStmt(s->thenBranch);
            if (s->elseBranch) prescanStmt(s->elseBranch);
            break;
        }
        case StmtKind::For: {
            auto* s = static_cast<ForStmt*>(stmt.get());
            prescanStmt(s->body);
            break;
        }
        case StmtKind::While: {
            auto* s = static_cast<WhileStmt*>(stmt.get());
            prescanStmt(s->body);
            break;
        }
        case StmtKind::Match: {
            auto* s = static_cast<MatchExpr*>(stmt.get());
            for (const auto& arm : s->arms) prescanStmt(arm.body);
            break;
        }
        default:
            break;
    }
}

void LLVMIRGenerator::emitEntryAllocas() {
    for (const auto& name : slotOrder_) {
        auto it = slots_.find(name);
        if (it == slots_.end() || !it->second.reg.empty()) continue;
        it->second.reg = newReg();
        irStream_ << "  " << it->second.reg << " = alloca "
                  << it->second.llvmTy << "\n";
    }
}

void LLVMIRGenerator::emitBlock(const std::vector<StmtPtr>& body) {
    pushScope();
    for (const auto& stmt : body) {
        if (!stmt) break;
        emitStmt(stmt);
        // Resilience: keep emitting after an error so one bad statement
        // doesn't hide errors in the rest of the block. Compilation still
        // fails at the end, but with every diagnosable problem listed.
    }
    popScope();
}

void LLVMIRGenerator::emitStmt(const StmtPtr& stmt) {
    if (!stmt) return;
    switch (stmt->kind()) {
        case StmtKind::Let:
            emitLet(static_cast<LetStmt*>(stmt.get()));
            break;
        case StmtKind::Mut:
            emitMut(static_cast<MutStmt*>(stmt.get()));
            break;
        case StmtKind::Assign:
            emitAssign(static_cast<AssignStmt*>(stmt.get()));
            break;
        case StmtKind::Return:
            emitReturn(static_cast<ReturnStmt*>(stmt.get()));
            break;
        case StmtKind::If:
            emitIf(static_cast<IfStmt*>(stmt.get()));
            break;
        case StmtKind::For:
            emitFor(static_cast<ForStmt*>(stmt.get()));
            break;
        case StmtKind::While:
            emitWhile(static_cast<WhileStmt*>(stmt.get()));
            break;
        case StmtKind::Break:
            emitBreak(static_cast<BreakStmt*>(stmt.get()));
            break;
        case StmtKind::Continue:
            emitContinue(static_cast<ContinueStmt*>(stmt.get()));
            break;
        case StmtKind::Expr:
        case StmtKind::Expression:
            emitExpression(static_cast<ExprStmt*>(stmt.get()));
            break;
        case StmtKind::Block: {
            auto* b = static_cast<BlockStmt*>(stmt.get());
            pushScope();
            for (const auto& s : b->body) {
                if (!s) break;
                emitStmt(s);
            }
            popScope();
            break;
        }
        case StmtKind::Match:
            emitMatch(static_cast<MatchExpr*>(stmt.get()));
            break;
        default:
            break;
    }
}

// ---- expressions ----

Val LLVMIRGenerator::emitExpr(const ExprPtr& expr) {
    if (!expr) return makeInt(0);
    switch (expr->kind()) {
        case ExprKind::Literal:
            return emitLiteral(static_cast<LiteralExpr*>(expr.get()));
        case ExprKind::Ident:
            return emitIdent(static_cast<IdentExpr*>(expr.get()));
        case ExprKind::BinaryOp:
            return emitBinaryOp(static_cast<BinaryOpExpr*>(expr.get()));
        case ExprKind::UnaryOp:
            return emitUnaryOp(static_cast<UnaryOpExpr*>(expr.get()));
        case ExprKind::Call:
            return emitCall(static_cast<CallExpr*>(expr.get()));
        case ExprKind::FieldAccess:
            return emitFieldAccess(static_cast<FieldAccessExpr*>(expr.get()));
        case ExprKind::StructLit:
            return emitStructLit(static_cast<StructLitExpr*>(expr.get()));
        case ExprKind::Range:
            return emitRange(static_cast<RangeExpr*>(expr.get()));
        case ExprKind::TypeCast:
            return emitTypeCast(static_cast<TypeCastExpr*>(expr.get()));
        case ExprKind::StringInterp:
            return emitStringInterp(static_cast<StringInterpExpr*>(expr.get()));
        case ExprKind::ArrayLit:
            return emitArrayLit(static_cast<ArrayLitExpr*>(expr.get()));
        case ExprKind::Index:
            return emitIndex(static_cast<IndexExpr*>(expr.get()));
        case ExprKind::Conditional: {
            auto* ce = static_cast<ConditionalExpr*>(expr.get());
            Val c = materialize(emitExpr(ce->cond), "i1");
            Val tv = emitExpr(ce->thenValue);
            Val ev = emitExpr(ce->elseValue);
            // Common type: string > float > int; bool stays bool
            VT common = (tv.type == VT::Str || ev.type == VT::Str) ? VT::Str
                      : (tv.type == VT::Float || ev.type == VT::Float) ? VT::Float
                      : (tv.type == VT::Bool && ev.type == VT::Bool) ? VT::Bool
                      : VT::Int;
            const std::string ty = vtLLVM(common);
            tv = materialize(tv, ty);
            ev = materialize(ev, ty);
            std::string r = newReg();
            irStream_ << "  " << r << " = select i1 " << c.ref << ", " << ty
                      << " " << tv.ref << ", " << ty << " " << ev.ref << "\n";
            return Val{r, common, ""};
        }
        default:
            error("Unsupported expression kind", expr->line, expr->col);
            return makeInt(0);
    }
}

Val LLVMIRGenerator::emitLiteral(const LiteralExpr* lit) {
    const ClassifyResult& val = lit->val;
    switch (val.kind) {
        case ClassifyResult::Integer:
            return makeInt(val.intVal);
        case ClassifyResult::Float:
            return Val{fmtDouble(val.floatVal), VT::Float, ""};
        case ClassifyResult::Bool:
            return val.intVal ? Val{"1", VT::Bool, ""} : Val{"0", VT::Bool, ""};
        case ClassifyResult::String:
            return stringConstant(val.strVal);
        case ClassifyResult::Char:
            return makeInt(val.strVal.empty() ? 0
                                              : static_cast<unsigned char>(val.strVal[0]));
        default:
            return makeInt(0); // none literal
    }
}

Val LLVMIRGenerator::emitIdent(const IdentExpr* ident) {
    // Enum variant reference? (Color.Red never reaches here — that is FieldAccess.)
    for (const auto& [ename, variants] : enums_) {
        (void)ename;
        auto it = std::find(variants.begin(), variants.end(), ident->name);
        if (it != variants.end()) {
            return makeInt(static_cast<int64_t>(it - variants.begin()));
        }
    }
    if (hasSlot(ident->name)) {
        return loadVar(ident->name, ident->line, ident->col);
    }
    error("Undefined variable: " + ident->name, ident->line, ident->col);
    return makeInt(0);
}

Val LLVMIRGenerator::emitBinaryOp(const BinaryOpExpr* op) {
    Val l = emitExpr(op->left);
    Val r = emitExpr(op->right);

    const bool cmp = op->op == TokenType::EQ || op->op == TokenType::NEQ ||
                     op->op == TokenType::LT || op->op == TokenType::GT ||
                     op->op == TokenType::LTE || op->op == TokenType::GTE;

    // String concatenation / comparison
    if (l.type == VT::Str || r.type == VT::Str) {
        if (op->op == TokenType::PLUS) {
            return concatStrings(toStringVal(l), toStringVal(r));
        }
        if (cmp) {
            std::string ls = toStringVal(l).ref;
            std::string rs = toStringVal(r).ref;
            std::string c = newReg();
            irStream_ << "  " << c << " = call i32 @strcmp(ptr " << ls
                      << ", ptr " << rs << ")\n";
            // EQ/NEQ compare against 0; LT/GT/LTE/GTE use the sign of strcmp.
            std::string mnemonic;
            switch (op->op) {
                case TokenType::NEQ: mnemonic = "ne"; break;
                case TokenType::LT: mnemonic = "slt"; break;
                case TokenType::GT: mnemonic = "sgt"; break;
                case TokenType::LTE: mnemonic = "sle"; break;
                case TokenType::GTE: mnemonic = "sge"; break;
                default: mnemonic = "eq"; break;
            }
            std::string eq = newReg();
            irStream_ << "  " << eq << " = icmp " << mnemonic << " i32 "
                      << c << ", 0\n";
            return Val{eq, VT::Bool, ""};
        }
        error("Invalid operation on strings", op->line, op->col);
        return makeInt(0);
    }

    // Floating point path
    if (l.type == VT::Float || r.type == VT::Float) {
        l = materialize(l, "double");
        r = materialize(r, "double");
        std::string mnem;
        switch (op->op) {
            case TokenType::PLUS: mnem = "fadd"; break;
            case TokenType::MINUS: mnem = "fsub"; break;
            case TokenType::STAR: mnem = "fmul"; break;
            case TokenType::SLASH: mnem = "fdiv"; break;
            case TokenType::EQ: mnem = "fcmp oeq"; break;
            case TokenType::NEQ: mnem = "fcmp one"; break;
            case TokenType::LT: mnem = "fcmp olt"; break;
            case TokenType::GT: mnem = "fcmp ogt"; break;
            case TokenType::LTE: mnem = "fcmp ole"; break;
            case TokenType::GTE: mnem = "fcmp oge"; break;
            default:
                error("Unsupported float operator", op->line, op->col);
                return makeInt(0);
        }
        std::string res = newReg();
        irStream_ << "  " << res << " = " << mnem << " double " << l.ref
                  << ", " << r.ref << "\n";
        return cmp ? Val{res, VT::Bool, ""} : Val{res, VT::Float, ""};
    }

    // Logical operators on i1
    if (op->op == TokenType::AND || op->op == TokenType::OR) {
        l = materialize(l, "i1");
        r = materialize(r, "i1");
        std::string res = newReg();
        irStream_ << "  " << res << " = " << (op->op == TokenType::AND ? "and" : "or")
                  << " i1 " << l.ref << ", " << r.ref << "\n";
        return Val{res, VT::Bool, ""};
    }

    // Integer path
    l = materialize(l, "i32");
    r = materialize(r, "i32");
    std::string mnem;
    switch (op->op) {
        case TokenType::PLUS: mnem = "add"; break;
        case TokenType::MINUS: mnem = "sub"; break;
        case TokenType::STAR: mnem = "mul"; break;
        case TokenType::SLASH: mnem = "sdiv"; break;
        case TokenType::MOD: mnem = "srem"; break;
        case TokenType::EQ: mnem = "icmp eq"; break;
        case TokenType::NEQ: mnem = "icmp ne"; break;
        case TokenType::LT: mnem = "icmp slt"; break;
        case TokenType::GT: mnem = "icmp sgt"; break;
        case TokenType::LTE: mnem = "icmp sle"; break;
        case TokenType::GTE: mnem = "icmp sge"; break;
        default:
            error("Unknown binary operator", op->line, op->col);
            return makeInt(0);
    }
    std::string res = newReg();
    irStream_ << "  " << res << " = " << mnem << " i32 " << l.ref << ", " << r.ref << "\n";
    return cmp ? Val{res, VT::Bool, ""} : Val{res, VT::Int, ""};
}

Val LLVMIRGenerator::emitUnaryOp(const UnaryOpExpr* op) {
    Val operand = emitExpr(op->operand);
    switch (op->op) {
        case TokenType::NOT: {
            operand = materialize(operand, "i1");
            std::string res = newReg();
            irStream_ << "  " << res << " = xor i1 " << operand.ref << ", true\n";
            return Val{res, VT::Bool, ""};
        }
        case TokenType::MINUS: {
            if (operand.type == VT::Float) {
                operand = materialize(operand, "double");
                std::string res = newReg();
                irStream_ << "  " << res << " = fneg double " << operand.ref << "\n";
                return Val{res, VT::Float, ""};
            }
            operand = materialize(operand, "i32");
            std::string res = newReg();
            irStream_ << "  " << res << " = sub i32 0, " << operand.ref << "\n";
            return Val{res, VT::Int, ""};
        }
        case TokenType::PLUS:
            return operand;
        default:
            error("Unknown unary operator", op->line, op->col);
            return makeInt(0);
    }
}

Val LLVMIRGenerator::emitCall(const CallExpr* call) {
    // Method call: callee is a field access (obj.method(args))
    if (auto* fa = dynamic_cast<FieldAccessExpr*>(call->callee.get())) {
        // Python-style list methods on local arrays
        if (auto* arrId = dynamic_cast<IdentExpr*>(fa->obj.get())) {
            auto asit = slots_.find(arrId->name);
            if (asit != slots_.end() && asit->second.vt == VT::ArrayPtr &&
                fa->field == "append") {
                return emitListAppend(asit->second, arrId->name, call);
            }
        }
        std::string owner;
        Val recv;
        bool hasRecv = false;
        bool staticCall = false;

        if (auto* objId = dynamic_cast<IdentExpr*>(fa->obj.get())) {
            if (structs_.count(objId->name)) {
                // Static-style reference: Point.make(...)
                owner = objId->name;
                staticCall = true;
            } else if (objId->name == "self" && !curSelfType_.empty() && hasSlot("self")) {
                recv = loadVar("self", call->line, call->col);
                owner = curSelfType_;
                hasRecv = true;
            }
        }
        if (!staticCall && owner.empty()) {
            recv = emitExpr(fa->obj);
            if (recv.type == VT::StructPtr && !recv.typeName.empty()) {
                owner = recv.typeName;
                hasRecv = true;
            } else if (methodOwner_.count(fa->field)) {
                owner = methodOwner_[fa->field];
                hasRecv = true;
            }
        }
        if (owner.empty() || !methods_.count(owner + "." + fa->field)) {
            error("Unknown method: " + fa->field, call->line, call->col);
            return makeInt(0);
        }
        const std::string key = owner + "." + fa->field;
        const FunctionDecl* mdecl = methods_[key];
        auto sit = sigs_.find(key);
        FnSig sig = sit != sigs_.end() ? sit->second : FnSig{};
        if (sig.params.empty()) {
            for (const auto& [pn, pt] : mdecl->params) {
                (void)pn;
                sig.params.push_back(getTypeStr(pt));
            }
            sig.ret = getTypeStr(mdecl->returnType);
        }

        std::vector<Val> argv;
        if (hasRecv) argv.push_back(recv);
        for (const auto& arg : call->args) argv.push_back(emitExpr(arg));

        std::string args;
        for (size_t i = 0; i < argv.size(); ++i) {
            Val v = argv[i];
            std::string ty = i < sig.params.size() ? sig.params[i]
                                                   : vtLLVM(v.type);
            v = materialize(v, ty);
            if (i) args += ", ";
            args += ty + " " + v.ref;
        }

        std::string res = newReg();
        irStream_ << "  " << res << " = call " << (sig.ret.empty() ? "i32" : sig.ret)
                  << " @" << sanitize(owner) << "_" << sanitize(fa->field) << "("
                  << args << ")\n";

        VT rt = mdecl->returnType ? vtOfType(mdecl->returnType) : VT::Int;
        std::string rtn = mdecl->returnType ? mdecl->returnType->getName() : "";
        if (sig.ret == "void") return Val{res, VT::Void, ""};
        return Val{res, rt, rtn};
    }

    auto* ident = dynamic_cast<IdentExpr*>(call->callee.get());
    if (!ident) {
        error("Cannot determine call target", call->line, call->col);
        return makeInt(0);
    }
    const std::string& fnName = ident->name;

    // ---- builtins ----
    if (fnName == "print") {
        std::string text;
        bool first = true;
        for (const auto& arg : call->args) {
            Val v = toStringVal(emitExpr(arg));
            if (first) {
                text = v.ref;
                first = false;
            } else {
                Val sp = concatStrings(Val{text, VT::Str, ""}, stringConstant(" "));
                text = concatStrings(sp, v).ref;
            }
        }
        if (first) text = stringConstant("").ref;
        std::string res = newReg();
        irStream_ << "  " << res << " = call i32 (ptr, ...) @printf(ptr @.fmt.print, ptr "
                  << text << ")\n";
        return Val{res, VT::Int, ""};
    }
    if (fnName == "str" && call->args.size() == 1) {
        return toStringVal(emitExpr(call->args[0]));
    }
    if (fnName == "len" && call->args.size() == 1) {
        // Python-style: len(list) reads the runtime header; len(string) = strlen.
        if (auto* argId = dynamic_cast<IdentExpr*>(call->args[0].get())) {
            auto sit = slots_.find(argId->name);
            if (sit != slots_.end() && sit->second.vt == VT::ArrayPtr) {
                // Slot holds a POINTER to the list header — deref first.
                std::string p = newReg();
                irStream_ << "  " << p << " = load ptr, ptr "
                          << sit->second.reg << "\n";
                std::string l64 = newReg();
                irStream_ << "  " << l64 << " = load i64, ptr " << p << "\n";
                std::string t = newReg();
                irStream_ << "  " << t << " = trunc i64 " << l64 << " to i32\n";
                return Val{t, VT::Int, ""};
            }
        }
        Val a = emitExpr(call->args[0]);
        if (a.type == VT::ArrayPtr) {
            // list passed as an expression (param use inside functions)
            std::string l64 = newReg();
            irStream_ << "  " << l64 << " = load i64, ptr " << a.ref << "\n";
            std::string t = newReg();
            irStream_ << "  " << t << " = trunc i64 " << l64 << " to i32\n";
            return Val{t, VT::Int, ""};
        }
        if (a.type == VT::Str) {
            std::string n = newReg();
            irStream_ << "  " << n << " = call i64 @strlen(ptr " << a.ref << ")\n";
            std::string t = newReg();
            irStream_ << "  " << t << " = trunc i64 " << n << " to i32\n";
            return Val{t, VT::Int, ""};
        }
        error("len() expects a list or a string", call->line, call->col);
        return makeInt(0);
    }
    if (fnName == "println") {
        // alias of print (print already appends a newline)
        auto ident = std::make_shared<IdentExpr>("print", call->line, call->col);
        CallExpr asPrint(ident, call->args, call->line, call->col);
        return emitCall(&asPrint);
    }
    if (fnName == "input" && call->args.empty()) {
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_input()\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "int" && call->args.size() == 1) {
        Val v = emitExpr(call->args[0]);
        if (v.type == VT::Str) {
            v = materialize(v, "ptr");
            std::string res = newReg();
            irStream_ << "  " << res << " = call i32 @atoi(ptr " << v.ref << ")\n";
            return Val{res, VT::Int, ""};
        }
        return materialize(v, "i32"); // numeric pass-through/truncation
    }
    if (fnName == "float" && call->args.size() == 1) {
        Val v = emitExpr(call->args[0]);
        if (v.type == VT::Str) {
            v = materialize(v, "ptr");
            std::string res = newReg();
            irStream_ << "  " << res << " = call double @atof(ptr " << v.ref << ")\n";
            return Val{res, VT::Float, ""};
        }
        return materialize(v, "double");
    }
    if (fnName == "abs" && call->args.size() == 1) {
        Val v = emitExpr(call->args[0]);
        if (v.type == VT::Float) {
            v = materialize(v, "double");
            std::string neg = newReg();
            irStream_ << "  " << neg << " = fneg double " << v.ref << "\n";
            std::string c = newReg();
            irStream_ << "  " << c << " = fcmp olt double " << v.ref << ", 0.0\n";
            std::string r = newReg();
            irStream_ << "  " << r << " = select i1 " << c << ", double " << neg
                      << ", double " << v.ref << "\n";
            return Val{r, VT::Float, ""};
        }
        v = materialize(v, "i32");
        std::string c = newReg();
        irStream_ << "  " << c << " = icmp slt i32 " << v.ref << ", 0\n";
        std::string neg = newReg();
        irStream_ << "  " << neg << " = sub i32 0, " << v.ref << "\n";
        std::string r = newReg();
        irStream_ << "  " << r << " = select i1 " << c << ", i32 " << neg
                  << ", i32 " << v.ref << "\n";
        return Val{r, VT::Int, ""};
    }
    if ((fnName == "min" || fnName == "max") && call->args.size() == 2) {
        Val a = emitExpr(call->args[0]);
        Val b = emitExpr(call->args[1]);
        const bool isMax = fnName == "max";
        if (a.type == VT::Float || b.type == VT::Float) {
            a = materialize(a, "double");
            b = materialize(b, "double");
            std::string c = newReg();
            irStream_ << "  " << c << " = fcmp o" << (isMax ? "gt" : "lt")
                      << " double " << a.ref << ", " << b.ref << "\n";
            std::string r = newReg();
            irStream_ << "  " << r << " = select i1 " << c << ", double " << a.ref
                      << ", double " << b.ref << "\n";
            return Val{r, VT::Float, ""};
        }
        a = materialize(a, "i32");
        b = materialize(b, "i32");
        std::string c = newReg();
        irStream_ << "  " << c << " = icmp s" << (isMax ? "gt" : "lt")
                  << " i32 " << a.ref << ", " << b.ref << "\n";
        std::string r = newReg();
        irStream_ << "  " << r << " = select i1 " << c << ", i32 " << a.ref
                  << ", i32 " << b.ref << "\n";
        return Val{r, VT::Int, ""};
    }
    if (call->args.size() == 1 &&
        (fnName == "sqrt" || fnName == "floor" || fnName == "ceil")) {
        Val v = materialize(emitExpr(call->args[0]), "double");
        std::string res = newReg();
        irStream_ << "  " << res << " = call double @" << fnName << "(double "
                  << v.ref << ")\n";
        return Val{res, VT::Float, ""};
    }
    if (fnName == "pow" && call->args.size() == 2) {
        Val a = materialize(emitExpr(call->args[0]), "double");
        Val b = materialize(emitExpr(call->args[1]), "double");
        std::string res = newReg();
        irStream_ << "  " << res << " = call double @pow(double " << a.ref
                  << ", double " << b.ref << ")\n";
        return Val{res, VT::Float, ""};
    }
    if ((fnName == "upper" || fnName == "lower") && call->args.size() == 1) {
        Val v = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_case_map(ptr " << v.ref
                  << ", i1 " << (fnName == "upper" ? "true" : "false") << ")\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "contains" && call->args.size() == 2) {
        Val h = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        Val n = materialize(toStringVal(emitExpr(call->args[1])), "ptr");
        std::string found = newReg();
        irStream_ << "  " << found << " = call ptr @strstr(ptr " << h.ref
                  << ", ptr " << n.ref << ")\n";
        std::string r = newReg();
        irStream_ << "  " << r << " = icmp ne ptr " << found << ", null\n";
        return Val{r, VT::Bool, ""};
    }
    if (fnName == "ord" && call->args.size() == 1) {
        Val v = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string b8 = newReg();
        irStream_ << "  " << b8 << " = load i8, ptr " << v.ref << "\n";
        std::string r = newReg();
        irStream_ << "  " << r << " = zext i8 " << b8 << " to i32\n";
        return Val{r, VT::Int, ""};
    }
    if (fnName == "chr" && call->args.size() == 1) {
        Val v = materialize(emitExpr(call->args[0]), "i32");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_chr(i32 " << v.ref << ")\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "read_file" && call->args.size() == 1) {
        Val p = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_read_file(ptr " << p.ref << ")\n";
        return Val{res, VT::Str, ""};
    }
    if ((fnName == "write_file" || fnName == "append_file") && call->args.size() == 2) {
        Val p = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        Val d = materialize(toStringVal(emitExpr(call->args[1])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call i1 @eng_write_file(ptr " << p.ref
                  << ", ptr " << d.ref << ", i1 "
                  << (fnName == "append_file" ? "true" : "false") << ")\n";
        return Val{res, VT::Bool, ""};
    }
    if (fnName == "file_exists" && call->args.size() == 1) {
        Val p = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call i1 @eng_file_exists(ptr " << p.ref << ")\n";
        return Val{res, VT::Bool, ""};
    }
    if (fnName == "delete_file" && call->args.size() == 1) {
        Val p = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string rc = newReg();
        irStream_ << "  " << rc << " = call i32 @remove(ptr " << p.ref << ")\n";
        std::string res = newReg();
        irStream_ << "  " << res << " = icmp eq i32 " << rc << ", 0\n";
        return Val{res, VT::Bool, ""};
    }
    // ---- OS builtins: shell commands & app launching ----
    if (fnName == "run_command" && call->args.size() == 1) {
        Val c = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call i32 @eng_run_command(ptr " << c.ref << ")\n";
        return Val{res, VT::Int, ""};
    }
    if (fnName == "exec_output" && call->args.size() == 1) {
        Val c = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_exec_output(ptr " << c.ref << ")\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "open_app" && call->args.size() == 1) {
        Val a = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call i1 @eng_open_app(ptr " << a.ref << ")\n";
        return Val{res, VT::Bool, ""};
    }
    // ---- hardware chat: serial port ----
    if (fnName == "serial_open" && call->args.size() == 2) {
        Val p = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        Val b = materialize(emitExpr(call->args[1]), "i32");
        std::string res = newReg();
        irStream_ << "  " << res << " = call i1 @eng_serial_open(ptr " << p.ref
                  << ", i32 " << b.ref << ")\n";
        return Val{res, VT::Bool, ""};
    }
    if (fnName == "serial_write" && call->args.size() == 1) {
        Val d = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call i1 @eng_serial_write(ptr " << d.ref << ")\n";
        return Val{res, VT::Bool, ""};
    }
    if (fnName == "serial_read_line" && call->args.empty()) {
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_serial_read_line()\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "serial_close" && call->args.empty()) {
        std::string res = newReg();
        irStream_ << "  " << res << " = call i32 @eng_serial_close()\n";
        return Val{res, VT::Int, ""};
    }
    // ---- OS helpers: sleep, env, cwd, path ----
    if (fnName == "sleep" && call->args.size() == 1) {
        Val ms = materialize(emitExpr(call->args[0]), "i32");
        irStream_ << "  call void @eng_sleep(i32 " << ms.ref << ")\n";
        return Val{"", VT::Void, ""};
    }
    if (fnName == "env_get" && call->args.size() == 1) {
        Val n = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_env_get(ptr " << n.ref << ")\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "cwd" && call->args.empty()) {
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_cwd()\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "path_join" && call->args.size() == 2) {
        Val b = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        Val r = materialize(toStringVal(emitExpr(call->args[1])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_path_join(ptr " << b.ref
                  << ", ptr " << r.ref << ")\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "substring" && call->args.size() == 3) {
        Val s = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        Val st = materialize(emitExpr(call->args[1]), "i64");
        Val ln = materialize(emitExpr(call->args[2]), "i64");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_substr(ptr " << s.ref
                  << ", i64 " << st.ref << ", i64 " << ln.ref << ")\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "repeat" && call->args.size() == 2) {
        Val s = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        Val n = materialize(emitExpr(call->args[1]), "i64");
        std::string res = newReg();
        irStream_ << "  " << res << " = call ptr @eng_repeat(ptr " << s.ref
                  << ", i64 " << n.ref << ")\n";
        return Val{res, VT::Str, ""};
    }
    if (fnName == "len" && call->args.size() == 1) {
        Val v = materialize(toStringVal(emitExpr(call->args[0])), "ptr");
        std::string res = newReg();
        irStream_ << "  " << res << " = call i64 @strlen(ptr " << v.ref << ")\n";
        std::string t = newReg();
        irStream_ << "  " << t << " = trunc i64 " << res << " to i32\n";
        return Val{t, VT::Int, ""};
    }
    if (fnName == "assert" && call->args.size() == 1) {
        Val c = materialize(emitExpr(call->args[0]), "i1");
        std::string okL = label("assert.ok");
        std::string failL = label("assert.fail");
        irStream_ << "  br i1 " << c.ref << ", label %" << okL << ", label %" << failL << "\n";
        irStream_ << failL << ":\n";
        Val msg = stringConstant("assertion failed");
        std::string pr = newReg(); // assign result: bare non-void calls break LLVM's
        irStream_ << "  " << pr    // implicit value numbering vs our numeric regs
                  << " = call i32 (ptr, ...) @printf(ptr @.fmt.print, ptr "
                  << msg.ref << ")\n";
        irStream_ << "  call void @abort()\n";
        irStream_ << "  unreachable\n";
        irStream_ << okL << ":\n";
        return makeInt(1);
    }

    // ---- user functions ----
    auto fit = functions_.find(fnName);
    if (fit == functions_.end()) {
        error("Unknown function: " + fnName, call->line, call->col);
        return makeInt(0);
    }
    const FunctionDecl* decl = fit->second;
    auto sit = sigs_.find(fnName);
    FnSig sig = sit != sigs_.end() ? sit->second : FnSig{};
    if (sig.params.empty() && !call->args.empty()) {
        for (const auto& [pn, pt] : decl->params) {
            (void)pn;
            sig.params.push_back(getTypeStr(pt));
        }
        sig.ret = getTypeStr(decl->returnType);
    }

    std::string args;
    for (size_t i = 0; i < call->args.size(); ++i) {
        Val v = emitExpr(call->args[i]);
        std::string ty = i < sig.params.size() ? sig.params[i]
                                               : vtLLVM(v.type);
        v = materialize(v, ty);
        if (i) args += ", ";
        args += ty + " " + v.ref;
    }

    std::string res = newReg();
    std::string retTy = sig.ret.empty() ? "i32" : sig.ret;
    irStream_ << "  " << res << " = call " << retTy << " @"
              << sanitize(fnName) << "(" << args << ")\n";
    if (retTy == "void") return Val{res, VT::Void, ""};
    VT rt = decl->returnType ? vtOfType(decl->returnType) : VT::Int;
    std::string rtn = decl->returnType ? decl->returnType->getName() : "";
    return Val{res, rt, rtn};
}

Val LLVMIRGenerator::emitFieldAccess(const FieldAccessExpr* fa) {
    // Enum variant access: Color.Red
    if (auto* id = dynamic_cast<IdentExpr*>(fa->obj.get())) {
        auto eit = enums_.find(id->name);
        if (eit != enums_.end()) {
            auto vit = std::find(eit->second.begin(), eit->second.end(), fa->field);
            if (vit == eit->second.end()) {
                error("Unknown enum variant: " + id->name + "." + fa->field, fa->line, fa->col);
                return makeInt(0);
            }
            return makeInt(static_cast<int64_t>(vit - eit->second.begin()));
        }
    }

    Val addr = emitAddrOf(std::make_shared<FieldAccessExpr>(*fa));
    std::string ty = addr.typeName.empty() ? "i32" : getLLVMType(addr.typeName);
    if (addr.type == VT::Float) ty = "double";
    if (addr.type == VT::Bool) ty = "i1";
    if (addr.type == VT::Str || addr.type == VT::StructPtr) ty = "ptr";
    std::string res = newReg();
    irStream_ << "  " << res << " = load " << ty << ", ptr " << addr.ref << "\n";
    return Val{res, addr.type, addr.typeName};
}

Val LLVMIRGenerator::emitStructLit(const StructLitExpr* sl) {
    if (!structs_.count(sl->structName)) {
        error("Unknown struct: " + sl->structName, sl->line, sl->col);
        return makeInt(0);
    }
    std::string tmp = newReg();
    irStream_ << "  " << tmp << " = alloca " << llvmTypeName(sl->structName) << "\n";
    for (const auto& [fname, fexpr] : sl->fields) {
        std::string key = sl->structName + "." + fname;
        if (!fieldIndex_.count(key)) {
            error("Unknown field: " + key, sl->line, sl->col);
            continue;
        }
        int idx = fieldIndex_[key];
        Val v = emitExpr(fexpr);
        TypePtr fty;
        for (const auto& [dn, dt] : structs_[sl->structName]) {
            if (dn == fname) { fty = dt; break; }
        }
        std::string llvmTy = getLLVMType(fty ? fty->getName() : "int");
        v = materialize(v, llvmTy);
        std::string fp = newReg();
        irStream_ << "  " << fp << " = getelementptr inbounds "
                  << llvmTypeName(sl->structName) << ", ptr " << tmp
                  << ", i32 0, i32 " << idx << "\n";
        irStream_ << "  store " << llvmTy << " " << v.ref << ", ptr " << fp << "\n";
    }
    return Val{tmp, VT::StructPtr, sl->structName};
}

Val LLVMIRGenerator::emitRange(const RangeExpr* r) {
    error("Range expressions are only supported in for loops", r->line, r->col);
    return makeInt(0);
}

Val LLVMIRGenerator::emitTypeCast(const TypeCastExpr* tc) {
    Val v = emitExpr(tc->expr);
    if (!tc->targetType) return v;
    const std::string targetName = tc->targetType->getName();
    if (targetName == "string") return toStringVal(v);
    const std::string ty = getTypeStr(tc->targetType);
    v = materialize(v, ty);
    return Val{v.ref, vtOfType(tc->targetType),
               targetName};
}

Val LLVMIRGenerator::emitStringInterp(const StringInterpExpr* si) {
    Val acc;
    bool first = true;
    for (const auto& part : si->parts) {
        Val v = toStringVal(emitExpr(part));
        if (first) {
            acc = v;
            first = false;
        } else {
            acc = concatStrings(acc, v);
        }
    }
    return first ? stringConstant("") : acc;
}

static VT classifyElemVT(const Expr* e) {
    if (!e) return VT::Int;
    if (e->kind() == ExprKind::Literal) {
        auto* lit = static_cast<const LiteralExpr*>(e);
        switch (lit->val.kind) {
            case ClassifyResult::Float: return VT::Float;
            case ClassifyResult::Bool: return VT::Bool;
            case ClassifyResult::String: return VT::Str;
            default: return VT::Int;
        }
    }
    return VT::Int;
}

Val LLVMIRGenerator::emitArrayLit(const ArrayLitExpr* al) {    if (al->elems.empty()) {
        error("Empty array literals are not supported yet", al->line, al->col);
        return makeInt(0);
    }
    std::vector<Val> elems;
    elems.reserve(al->elems.size());
    for (const auto& e : al->elems) elems.push_back(emitExpr(e));

    // Element type from the first element.
    // Layout v2: [len:i64][e0][e1]...[en-1] — the pointer targets the header,
    // so len()/append()/for-in work across function boundaries.
    const VT elemVT = elems.front().type;
    const std::string elemTy = vtLLVM(elemVT);
    const int64_t count = static_cast<int64_t>(elems.size());

    std::string buf = newReg();
    irStream_ << "  " << buf << " = call ptr @malloc(i64 "
              << ((count + 1) * 8) << ")\n";
    irStream_ << "  store i64 " << count << ", ptr " << buf << "\n";

    for (int64_t i = 0; i < count; ++i) {
        Val v = materialize(elems[i], elemTy);
        std::string slot = newReg();
        irStream_ << "  " << slot << " = getelementptr inbounds i8, ptr "
                  << buf << ", i64 " << (8 + i * 8) << "\n";
        irStream_ << "  store " << elemTy << " " << v.ref << ", ptr " << slot << "\n";
    }
    return Val{buf, VT::ArrayPtr, "array"};
}

Val LLVMIRGenerator::emitIndex(const IndexExpr* ix) {
    Val base = emitExpr(ix->base);
    Val idx = emitExpr(ix->index);

    // Element type: known for named slots (set at let-initialization time),
    // otherwise assume i32 scalars from array literals.
    VT elemVT = VT::Int;
    std::string elemTy = "i32";
    if (auto* id = dynamic_cast<IdentExpr*>(ix->base.get())) {
        auto it = slots_.find(id->name);
        if (it != slots_.end()) {
            elemVT = it->second.elemVT;
            elemTy = vtLLVM(elemVT);
        }
    }

    Val idxI64 = materialize(idx, "i64");
    // Arrays: header(8) + idx*8. Strings: byte-wise.
    std::string byteOff;
    if (base.type == VT::Str) {
        byteOff = idxI64.ref;
    } else {
        std::string scaled = newReg();
        irStream_ << "  " << scaled << " = mul i64 " << idxI64.ref << ", 8\n";
        byteOff = newReg();
        irStream_ << "  " << byteOff << " = add i64 " << scaled
                  << ", 8\n"; // skip length header
    }
    std::string slot = newReg();
    irStream_ << "  " << slot << " = getelementptr inbounds i8, ptr "
              << base.ref << ", i64 " << byteOff << "\n";
    if (base.type == VT::Str) {
        // String indexing yields a single byte (char code)
        std::string b = newReg();
        irStream_ << "  " << b << " = load i8, ptr " << slot << "\n";
        std::string w = newReg();
        irStream_ << "  " << w << " = zext i8 " << b << " to i32\n";
        return Val{w, VT::Int, ""};
    }
    std::string res = newReg();
    irStream_ << "  " << res << " = load " << elemTy << ", ptr " << slot << "\n";
    return Val{res, elemVT, ""};
}

// ---- statements ----

void LLVMIRGenerator::emitLet(const LetStmt* stmt) {
    Val v = stmt->init ? emitExpr(stmt->init) : makeInt(0);
    auto it = slots_.find(stmt->name);
    if (it == slots_.end()) {
        declareSlot(stmt->name, stmt->type ? stmt->type : inferTypeOf(stmt->init.get()));
        emitEntryAllocas();
        it = slots_.find(stmt->name);
    }
    if (it != slots_.end()) {
        // Record array element type for later index access
        if (auto* al = dynamic_cast<ArrayLitExpr*>(stmt->init.get()); al && !al->elems.empty()) {
            it->second.elemVT = classifyElemVT(al->elems.front().get());
        }
        storeToSlot(it->second.reg, it->second.llvmTy, v);
    }
}

void LLVMIRGenerator::emitMut(const MutStmt* stmt) {
    Val v = stmt->init ? emitExpr(stmt->init) : makeInt(0);
    auto it = slots_.find(stmt->name);
    if (it == slots_.end()) {
        declareSlot(stmt->name, stmt->type ? stmt->type : inferTypeOf(stmt->init.get()));
        emitEntryAllocas();
        it = slots_.find(stmt->name);
    }
    if (it != slots_.end()) {
        storeToSlot(it->second.reg, it->second.llvmTy, v);
    }
}

void LLVMIRGenerator::emitAssign(const AssignStmt* stmt) {
    if (!stmt->value) return;
    Val v = emitExpr(stmt->value);
    if (stmt->target) {
        // Complex target: obj.field = value
        Val addr = emitAddrOf(stmt->target);
        std::string ty = addr.typeName.empty()
                             ? vtLLVM(addr.type)
                             : getLLVMType(addr.typeName);
        v = materialize(v, ty);
        irStream_ << "  store " << ty << " " << v.ref << ", ptr " << addr.ref << "\n";
        return;
    }
    storeByName(stmt->name, v, stmt->line, stmt->col);
}

void LLVMIRGenerator::emitReturn(const ReturnStmt* stmt) {
    hasReturn_ = true;
    if (!stmt->expr.has_value() || !stmt->expr.value()) {
        if (curRetTy_ == "void") irStream_ << "  ret void\n";
        else irStream_ << "  ret " << curRetTy_ << " zero\n";
        return;
    }
    Val v = emitExpr(stmt->expr.value());
    if (curRetTy_ == "void") {
        irStream_ << "  ret void\n";
        return;
    }
    v = materialize(v, curRetTy_);
    irStream_ << "  ret " << curRetTy_ << " " << v.ref << "\n";
}

void LLVMIRGenerator::emitIf(const IfStmt* stmt) {
    Val c = materialize(emitExpr(stmt->cond), "i1");
    std::string thenL = label("if.then");
    std::string endL = label("if.end");
    const bool hasElse = stmt->elseBranch != nullptr;
    std::string elseL = hasElse ? label("if.else") : endL;

    irStream_ << "  br i1 " << c.ref << ", label %" << thenL << ", label %" << elseL << "\n";
    irStream_ << thenL << ":\n";
    if (stmt->thenBranch) {
        if (stmt->thenBranch->kind() == StmtKind::Block) {
            emitBlock(static_cast<BlockStmt*>(stmt->thenBranch.get())->body);
        } else {
            emitStmt(stmt->thenBranch);
        }
    }
    if (!terminated()) irStream_ << "  br label %" << endL << "\n";

    if (hasElse) {
        irStream_ << elseL << ":\n";
        if (stmt->elseBranch->kind() == StmtKind::Block) {
            emitBlock(static_cast<BlockStmt*>(stmt->elseBranch.get())->body);
        } else {
            emitStmt(stmt->elseBranch);
        }
        if (!terminated()) irStream_ << "  br label %" << endL << "\n";
    }

    irStream_ << endL << ":\n";
}

Val LLVMIRGenerator::emitListAppend(Slot& arrSlot, const std::string& varName,
                                    const CallExpr* call) {
    (void)varName;
    if (call->args.size() != 1) {
        error("append expects exactly 1 argument", call->line, call->col);
        return makeInt(0);
    }
    Val v = emitExpr(call->args.front());
    const VT elemVT = arrSlot.elemVT;
    const std::string elemTy = vtLLVM(elemVT);

    // Layout v2: [len:i64][elems...]. Read the CURRENT length at runtime so
    // append works on params, globals and locals alike.
    std::string oldPtr = newReg();
    irStream_ << "  " << oldPtr << " = load ptr, ptr " << arrSlot.reg << "\n";
    std::string n64 = newReg();
    irStream_ << "  " << n64 << " = load i64, ptr " << oldPtr << "\n";
    std::string n32 = newReg();
    irStream_ << "  " << n32 << " = trunc i64 " << n64 << " to i32\n";

    // newBytes = 8 + (n+1)*8
    std::string np1 = newReg();
    irStream_ << "  " << np1 << " = add i64 " << n64 << ", 1\n";
    std::string bytes = newReg();
    irStream_ << "  " << bytes << " = mul i64 " << np1 << ", 8\n";
    std::string totalBytes = newReg();
    irStream_ << "  " << totalBytes << " = add i64 " << bytes << ", 8\n";

    std::string newPtr = newReg();
    irStream_ << "  " << newPtr << " = call ptr @malloc(i64 " << totalBytes << ")\n";
    // copy header + all elements: (n+1)*8 == bytes
    std::string mc = newReg();
    irStream_ << "  " << mc << " = call ptr @memcpy(ptr " << newPtr << ", ptr "
              << oldPtr << ", i64 " << bytes << ")\n";
    // NOTE: intentionally NOT freeing oldPtr — other bindings (caller args,
    // globals) may still view this buffer. Freeing here caused use-after-free
    // when append ran through a function param. Proper ownership/refcounting
    // arrives with the self-built backend; until then appends leak the old
    // block (bounded, deterministic, crash-free).

    // store element at offset 8 + n*8
    std::string elemOff = newReg();
    irStream_ << "  " << elemOff << " = mul i64 " << n64 << ", 8\n";
    std::string dstOff = newReg();
    irStream_ << "  " << dstOff << " = add i64 " << elemOff << ", 8\n";
    std::string dst = newReg();
    irStream_ << "  " << dst << " = getelementptr inbounds i8, ptr "
              << newPtr << ", i64 " << dstOff << "\n";
    v = materialize(v, elemTy);
    irStream_ << "  store " << elemTy << " " << v.ref << ", ptr " << dst << "\n";

    // update header length: n+1
    std::string nl = newReg();
    irStream_ << "  " << nl << " = add i64 " << n64 << ", 1\n";
    irStream_ << "  store i64 " << nl << ", ptr " << newPtr << "\n";
    irStream_ << "  store ptr " << newPtr << ", ptr " << arrSlot.reg << "\n";
    return makeInt(0); // Python-style: append returns none
}

void LLVMIRGenerator::emitFor(const ForStmt* stmt) {
    // for x in listName → iterate any list (length read from its header)
    if (auto* id = dynamic_cast<IdentExpr*>(stmt->iterable.get())) {
        auto asit = slots_.find(id->name);
        if (asit != slots_.end() && asit->second.vt == VT::ArrayPtr) {
            emitListFor(stmt, asit->second);
            return;
        }
    }
    auto* range = dynamic_cast<RangeExpr*>(stmt->iterable.get());
    if (!range) {
        error("for-in currently supports ranges and lists", stmt->line, stmt->col);
        return;
    }

    Val start = materialize(emitExpr(range->start), "i32");
    Val end = materialize(emitExpr(range->end), "i32");

    declareSlot(stmt->varName, std::make_shared<BasicType>("int"));
    emitEntryAllocas(); // no-op if already emitted; assigns reg for the loop var
    auto slotIt = slots_.find(stmt->varName);
    if (slotIt == slots_.end()) return;
    Slot varSlot = slotIt->second;

    irStream_ << "  store i32 " << start.ref << ", ptr " << varSlot.reg << "\n";

    std::string condL = label("for.cond");
    std::string bodyL = label("for.body");
    std::string incL = label("for.inc");
    std::string endL = label("for.end");

    irStream_ << "  br label %" << condL << "\n";
    irStream_ << condL << ":\n";
    std::string iv = newReg();
    irStream_ << "  " << iv << " = load i32, ptr " << varSlot.reg << "\n";
    std::string cond = newReg();
    irStream_ << "  " << cond << " = icmp "
              << (range->inclusive ? "sle" : "slt") << " i32 " << iv
              << ", " << end.ref << "\n";
    irStream_ << "  br i1 " << cond << ", label %" << bodyL << ", label %" << endL << "\n";

    irStream_ << bodyL << ":\n";
    loopStack_.push_back({endL, incL});
    if (stmt->body) {
        if (stmt->body->kind() == StmtKind::Block) {
            emitBlock(static_cast<BlockStmt*>(stmt->body.get())->body);
        } else {
            emitStmt(stmt->body);
        }
    }
    loopStack_.pop_back();
    if (!terminated()) irStream_ << "  br label %" << incL << "\n";

    irStream_ << incL << ":\n";
    std::string cv = newReg();
    irStream_ << "  " << cv << " = load i32, ptr " << varSlot.reg << "\n";
    std::string nv = newReg();
    irStream_ << "  " << nv << " = add i32 " << cv << ", 1\n";
    irStream_ << "  store i32 " << nv << ", ptr " << varSlot.reg << "\n";
    irStream_ << "  br label %" << condL << "\n";

    irStream_ << endL << ":\n";
}

void LLVMIRGenerator::emitListFor(const ForStmt* stmt, Slot& arrSlot) {
    TypePtr elTy;
    switch (arrSlot.elemVT) {
        case VT::Float: elTy = std::make_shared<BasicType>("float64"); break;
        case VT::Str:   elTy = std::make_shared<BasicType>("string"); break;
        case VT::Bool:  elTy = std::make_shared<BasicType>("bool"); break;
        default:        elTy = std::make_shared<BasicType>("int");
    }
    declareSlot(stmt->varName, elTy);
    declareSlot("__idx_" + stmt->varName, std::make_shared<BasicType>("int"));
    emitEntryAllocas();
    Slot varSlot = slots_[stmt->varName];
    Slot idxSlot = slots_["__idx_" + stmt->varName];

    std::string buf = newReg();
    irStream_ << "  " << buf << " = load ptr, ptr " << arrSlot.reg << "\n";
    // runtime length from the list header
    std::string n64 = newReg();
    irStream_ << "  " << n64 << " = load i64, ptr " << buf << "\n";
    std::string n32 = newReg();
    irStream_ << "  " << n32 << " = trunc i64 " << n64 << " to i32\n";
    irStream_ << "  store i32 0, ptr " << idxSlot.reg << "\n";

    const std::string condL = label("listfor.cond");
    const std::string bodyL = label("listfor.body");
    const std::string contL = label("listfor.cont");
    const std::string endL = label("listfor.end");

    irStream_ << "  br label %" << condL << "\n";
    irStream_ << condL << ":\n";
    std::string iv = newReg();
    irStream_ << "  " << iv << " = load i32, ptr " << idxSlot.reg << "\n";
    std::string cond = newReg();
    irStream_ << "  " << cond << " = icmp slt i32 " << iv << ", " << n32 << "\n";
    irStream_ << "  br i1 " << cond << ", label %" << bodyL << ", label %" << endL << "\n";

    irStream_ << bodyL << ":\n";
    loopStack_.push_back({endL, contL});

    std::string iv2 = newReg();
    irStream_ << "  " << iv2 << " = load i32, ptr " << idxSlot.reg << "\n";
    std::string off = newReg();
    irStream_ << "  " << off << " = sext i32 " << iv2 << " to i64\n";
    std::string scaled = newReg();
    irStream_ << "  " << scaled << " = mul i64 " << off << ", 8\n";
    std::string byteOff = newReg();
    irStream_ << "  " << byteOff << " = add i64 " << scaled << ", 8\n"; // skip header
    std::string ep = newReg();
    irStream_ << "  " << ep << " = getelementptr inbounds i8, ptr "
              << buf << ", i64 " << byteOff << "\n";
    const std::string elemTy = vtLLVM(arrSlot.elemVT);
    std::string ev = newReg();
    irStream_ << "  " << ev << " = load " << elemTy << ", ptr " << ep << "\n";
    Val evV{ev, arrSlot.elemVT, ""};
    evV = materialize(evV, varSlot.llvmTy);
    irStream_ << "  store " << varSlot.llvmTy << " " << evV.ref
              << ", ptr " << varSlot.reg << "\n";

    if (stmt->body) {
        if (stmt->body->kind() == StmtKind::Block) {
            emitBlock(static_cast<BlockStmt*>(stmt->body.get())->body);
        } else {
            emitStmt(stmt->body);
        }
    }
    loopStack_.pop_back();
    if (!terminated()) irStream_ << "  br label %" << contL << "\n";

    irStream_ << contL << ":\n";
    std::string cv = newReg();
    irStream_ << "  " << cv << " = load i32, ptr " << idxSlot.reg << "\n";
    std::string nv = newReg();
    irStream_ << "  " << nv << " = add i32 " << cv << ", 1\n";
    irStream_ << "  store i32 " << nv << ", ptr " << idxSlot.reg << "\n";
    irStream_ << "  br label %" << condL << "\n";

    irStream_ << endL << ":\n";
}

void LLVMIRGenerator::emitWhile(const WhileStmt* stmt) {
    std::string condL = label("while.cond");
    std::string bodyL = label("while.body");
    std::string endL = label("while.end");

    irStream_ << "  br label %" << condL << "\n";
    irStream_ << condL << ":\n";
    Val c = materialize(emitExpr(stmt->cond), "i1");
    irStream_ << "  br i1 " << c.ref << ", label %" << bodyL << ", label %" << endL << "\n";

    irStream_ << bodyL << ":\n";
    loopStack_.push_back({endL, condL});
    if (stmt->body) {
        if (stmt->body->kind() == StmtKind::Block) {
            emitBlock(static_cast<BlockStmt*>(stmt->body.get())->body);
        } else {
            emitStmt(stmt->body);
        }
    }
    loopStack_.pop_back();
    if (!terminated()) irStream_ << "  br label %" << condL << "\n";

    irStream_ << endL << ":\n";
}

void LLVMIRGenerator::emitBreak(const BreakStmt* stmt) {
    if (loopStack_.empty()) {
        error("break outside of loop", stmt->line, stmt->col);
        return;
    }
    irStream_ << "  br label %" << loopStack_.back().first << "\n";
}

void LLVMIRGenerator::emitContinue(const ContinueStmt* stmt) {
    if (loopStack_.empty()) {
        error("continue outside of loop", stmt->line, stmt->col);
        return;
    }
    irStream_ << "  br label %" << loopStack_.back().second << "\n";
}

void LLVMIRGenerator::emitExpression(const ExprStmt* stmt) {
    if (!stmt || !stmt->expr) return; // parser recovery may leave a null expr
    emitExpr(stmt->expr);
}

void LLVMIRGenerator::emitMatch(const MatchExpr* m) {
    Val scrut = emitExpr(m->scrutinee);
    std::string endL = label("match.end");

    if (m->arms.empty()) {
        irStream_ << "  br label %" << endL << "\n";
        irStream_ << endL << ":\n";
        return;
    }

    std::string nextL = label("match.case");
    irStream_ << "  br label %" << nextL << "\n";

    for (size_t i = 0; i < m->arms.size(); ++i) {
        const MatchArm& arm = m->arms[i];
        const bool wildcard = arm.pattern && arm.pattern->kind() == ExprKind::Ident &&
                              std::dynamic_pointer_cast<IdentExpr>(arm.pattern)->name == "_";

        std::string bodyL = label("match.body");
        std::string fallthroughL = label("match.case");

        irStream_ << nextL << ":\n";
        if (!wildcard && arm.pattern) {
            Val pat = emitExpr(arm.pattern);
            std::string cond;
            if (scrut.type == VT::Str || pat.type == VT::Str) {
                Val ls = materialize(toStringVal(scrut), "ptr");
                Val rs = materialize(toStringVal(pat), "ptr");
                std::string c = newReg();
                irStream_ << "  " << c << " = call i32 @strcmp(ptr " << ls.ref
                          << ", ptr " << rs.ref << ")\n";
                std::string eq = newReg();
                irStream_ << "  " << eq << " = icmp eq i32 " << c << ", 0\n";
                cond = eq;
            } else if (scrut.type == VT::Float || pat.type == VT::Float) {
                scrut = materialize(scrut, "double");
                pat = materialize(pat, "double");
                std::string eq = newReg();
                irStream_ << "  " << eq << " = fcmp oeq double " << scrut.ref
                          << ", " << pat.ref << "\n";
                cond = eq;
            } else {
                scrut = materialize(scrut, "i32");
                pat = materialize(pat, "i32");
                std::string eq = newReg();
                irStream_ << "  " << eq << " = icmp eq i32 " << scrut.ref
                          << ", " << pat.ref << "\n";
                cond = eq;
            }
            irStream_ << "  br i1 " << cond << ", label %" << bodyL
                      << ", label %" << fallthroughL << "\n";
        } else {
            irStream_ << "  br label %" << bodyL << "\n";
        }

        irStream_ << bodyL << ":\n";
        if (arm.body) {
            if (arm.body->kind() == StmtKind::Block) {
                emitBlock(static_cast<BlockStmt*>(arm.body.get())->body);
            } else {
                emitStmt(arm.body);
            }
        }
        if (!terminated()) irStream_ << "  br label %" << endL << "\n";
        nextL = fallthroughL;
    }

    irStream_ << nextL << ":\n";
    irStream_ << "  br label %" << endL << "\n";
    irStream_ << endL << ":\n";
    // Match is expression-based; emit a generic return to close function
    irStream_ << "  ret i32 0\n";
}

// ---- type helpers ----

std::string LLVMIRGenerator::getTypeStr(const TypePtr& type) {
    if (!type) return "i32";
    const std::string name = type->getName();
    if (name == "int") return "i32";
    if (name == "int8" || name == "i8") return "i8";
    if (name == "int16" || name == "i16") return "i16";
    if (name == "int32" || name == "i32") return "i32";
    if (name == "int64" || name == "i64") return "i64";
    if (name == "uint") return "i32";
    if (name == "uint8" || name == "u8") return "i8";
    if (name == "uint16" || name == "u16") return "i16";
    if (name == "uint32" || name == "u32") return "i32";
    if (name == "uint64" || name == "u64") return "i64";
    if (name == "float" || name == "float32" || name == "f32") return "float";
    if (name == "float64" || name == "f64" || name == "double") return "double";
    if (name == "bool") return "i1";
    if (name == "string" || name == "str") return "ptr";
    if (name == "char") return "i32";
    if (name == "byte") return "i8";
    if (name == "void") return "void";
    if (structs_.count(name)) return "ptr";
    if (name == "array" || name == "vector" || name == "map") return "ptr";
    return "i32";
}

std::string LLVMIRGenerator::getLLVMType(const std::string& ecType) {
    if (structs_.count(ecType)) return "ptr";
    return getTypeStr(std::make_shared<BasicType>(ecType));
}

VT LLVMIRGenerator::vtOfType(const TypePtr& type) const {
    if (!type) return VT::Int;
    const std::string name = type->getName();
    if (name == "int" || name == "int8" || name == "int16" ||
        name == "int32" || name == "int64" ||
        name == "uint" || name == "uint8" || name == "uint16" ||
        name == "uint32" || name == "uint64" || name == "char" ||
        name == "byte")
        return VT::Int;
    if (name == "float" || name == "float32" || name == "float64" ||
        name == "f32" || name == "f64" || name == "double")
        return VT::Float;
    if (name == "bool") return VT::Bool;
    if (name == "string" || name == "str") return VT::Str;
    if (structs_.count(name)) return VT::StructPtr;
    if (name == "array" || name == "vector" || name == "map") return VT::ArrayPtr;
    if (name == "void") return VT::Void;
    return VT::Unknown;
}

std::string LLVMIRGenerator::llvmTypeName(const std::string& structName) {
    return "%struct." + structName;
}

// ---- variable slots ----

void LLVMIRGenerator::declareSlot(const std::string& name, const TypePtr& type) {
    Slot s;
    s.llvmTy = getTypeStr(type);
    if (s.llvmTy == "void") s.llvmTy = "i32";
    s.vt = vtOfType(type);
    s.typeName = type ? type->getName() : "";

    auto it = slots_.find(name);
    if (it != slots_.end()) {
        // Redeclaration shadows in place; keep the existing alloca.
        if (it->second.reg.empty()) {
            s.reg = "";
        } else {
            s.reg = it->second.reg;
        }
        it->second = s;
        return;
    }
    slots_[name] = s;
    slotOrder_.push_back(name);
}

bool LLVMIRGenerator::hasSlot(const std::string& name) const {
    return slots_.count(name) != 0;
}

Val LLVMIRGenerator::loadVar(const std::string& name, int line, int col) {
    auto it = slots_.find(name);
    if (it == slots_.end()) {
        error("Undefined variable: " + name, line, col);
        return makeInt(0);
    }
    const Slot& s = it->second;
    std::string res = newReg();
    irStream_ << "  " << res << " = load " << s.llvmTy << ", ptr " << s.reg << "\n";
    return Val{res, s.vt, s.typeName};
}

void LLVMIRGenerator::storeToSlot(const std::string& slotReg, const std::string& llvmTy, const Val& v) {
    Val m = materialize(v, llvmTy);
    irStream_ << "  store " << llvmTy << " " << m.ref << ", ptr " << slotReg << "\n";
}

void LLVMIRGenerator::storeByName(const std::string& name, const Val& v, int line, int col) {
    auto it = slots_.find(name);
    if (it == slots_.end()) {
        error("Undefined variable: " + name, line, col);
        return;
    }
    storeToSlot(it->second.reg, it->second.llvmTy, v);
}

// ---- value helpers ----

std::string LLVMIRGenerator::newReg() {
    return "%" + std::to_string(++regCounter_);
}

Val LLVMIRGenerator::makeInt(int64_t v) {
    return Val{std::to_string(v), VT::Int, ""};
}

Val LLVMIRGenerator::materialize(const Val& v, const std::string& llvmTy) {
    const std::string have = vtLLVM(v.type);

    // Normalize double literals so they are valid IR float tokens.
    Val val = v;
    if (have == "double" && llvmTy == "double" && !val.ref.empty() && val.ref[0] != '%') {
        if (val.ref.find('.') == std::string::npos &&
            val.ref.find('e') == std::string::npos &&
            val.ref.find('n') == std::string::npos &&
            val.ref.find('i') == std::string::npos) {
            val.ref += ".0";
        }
        return val;
    }

    if (have == llvmTy) return val;

    std::string res = newReg();
    if (have == "i32" && llvmTy == "i1") {
        irStream_ << "  " << res << " = icmp ne i32 " << val.ref << ", 0\n";
        return Val{res, VT::Bool, ""};
    }
    if (have == "i32" && llvmTy == "i64") {
        irStream_ << "  " << res << " = sext i32 " << val.ref << " to i64\n";
        return Val{res, VT::Int, ""};
    }
    if (have == "i64" && llvmTy == "i32") {
        irStream_ << "  " << res << " = trunc i64 " << val.ref << " to i32\n";
        return Val{res, VT::Int, ""};
    }
    if (have == "i1" && llvmTy == "i32") {
        irStream_ << "  " << res << " = zext i1 " << val.ref << " to i32\n";
        return Val{res, VT::Int, ""};
    }
    if (have == "i8" && llvmTy == "i32") {
        irStream_ << "  " << res << " = sext i8 " << val.ref << " to i32\n";
        return Val{res, VT::Int, ""};
    }
    if (have == "i32" && llvmTy == "i8") {
        irStream_ << "  " << res << " = trunc i32 " << val.ref << " to i8\n";
        return Val{res, VT::Int, ""};
    }
    if (have == "i32" && llvmTy == "double") {
        irStream_ << "  " << res << " = sitofp i32 " << val.ref << " to double\n";
        return Val{res, VT::Float, ""};
    }
    if (have == "i1" && llvmTy == "double") {
        irStream_ << "  " << res << " = sitofp i1 " << val.ref << " to double\n";
        return Val{res, VT::Float, ""};
    }
    if (have == "double" && llvmTy == "i32") {
        irStream_ << "  " << res << " = fptosi double " << val.ref << " to i32\n";
        return Val{res, VT::Int, ""};
    }
    if (have == "double" && llvmTy == "i1") {
        std::string z = newReg();
        irStream_ << "  " << z << " = fcmp one double " << val.ref << ", 0.0\n";
        return Val{z, VT::Bool, ""};
    }
    if (have == "ptr" && llvmTy == "i32") {
        irStream_ << "  " << res << " = ptrtoint ptr " << val.ref << " to i32\n";
        return Val{res, VT::Int, ""};
    }
    if (have == "i32" && llvmTy == "ptr") {
        irStream_ << "  " << res << " = inttoptr i32 " << val.ref << " to ptr\n";
        return Val{res, VT::Str, ""};
    }

    error("Cannot convert value for use as " + llvmTy);
    return makeInt(0);
}

Val LLVMIRGenerator::toStringVal(const Val& v) {
    switch (v.type) {
        case VT::Str:
            return v;
        case VT::Int: {
            Val m = materialize(v, "i32");
            std::string res = newReg();
            irStream_ << "  " << res << " = call ptr @eng_int_to_str(i32 " << m.ref << ")\n";
            return Val{res, VT::Str, ""};
        }
        case VT::Float: {
            Val m = materialize(v, "double");
            std::string res = newReg();
            irStream_ << "  " << res << " = call ptr @eng_float_to_str(double " << m.ref << ")\n";
            return Val{res, VT::Str, ""};
        }
        case VT::Bool: {
            Val m = materialize(v, "i1");
            std::string res = newReg();
            irStream_ << "  " << res << " = call ptr @eng_bool_to_str(i1 " << m.ref << ")\n";
            return Val{res, VT::Str, ""};
        }
        case VT::StructPtr: {
            error("Cannot convert struct value to string");
            return stringConstant("");
        }
        default:
            error("Cannot convert value to string");
            return stringConstant("");
    }
}

// ---- strings ----

Val LLVMIRGenerator::stringConstant(const std::string& content) {
    auto it = stringConsts_.find(content);
    if (it == stringConsts_.end()) {
        // Late constant: register now, emit the global at end of module
        // (LLVM IR allows globals to be declared after their uses).
        std::string gvName = "@.str." + std::to_string(stringConsts_.size());
        stringConsts_[content] = {gvName, static_cast<int>(content.size())};
        pendingStrings_.push_back(content);
        it = stringConsts_.find(content);
    }
    // With opaque pointers a global's address IS a ptr — usable directly.
    return Val{it->second.first, VT::Str, ""};
}

Val LLVMIRGenerator::concatStrings(const Val& a, const Val& b) {
    Val pa = materialize(a, "ptr");
    Val pb = materialize(b, "ptr");
    std::string res = newReg();
    irStream_ << "  " << res << " = call ptr @eng_str_concat(ptr " << pa.ref
              << ", ptr " << pb.ref << ")\n";
    return Val{res, VT::Str, ""};
}

std::string LLVMIRGenerator::escapeLLVMString(const std::string& s) {
    static const char* hex = "0123456789ABCDEF";
    std::string result;
    for (unsigned char c : s) {
        if (c == '"' || c == '\\') {
            // Never emit \" or \\ — some LLVM frontends (zig cc) mis-parse
            // them inside c"..." strings. Hex escapes are unambiguous.
            result += '\\';
            result += hex[(c >> 4) & 0xF];
            result += hex[c & 0xF];
        } else if (c >= 32 && c <= 126) {
            result += static_cast<char>(c);
        } else {
            result += '\\';
            result += hex[(c >> 4) & 0xF];
            result += hex[c & 0xF];
        }
    }
    return result;
}

void LLVMIRGenerator::collectStrings(const std::vector<StmtPtr>& topLevel, std::vector<std::string>& out) {
    for (const auto& stmt : topLevel) collectStringsFromStmt(stmt, out);
}

void LLVMIRGenerator::collectStringsFromStmt(const StmtPtr& stmt, std::vector<std::string>& out) {
    if (!stmt) return;
    switch (stmt->kind()) {
        case StmtKind::FunctionDecl:
            collectStrings(static_cast<FunctionDecl*>(stmt.get())->body, out);
            break;
        case StmtKind::Impl: {
            auto* im = static_cast<ImplDecl*>(stmt.get());
            for (const auto& m : im->methods) collectStringsFromStmt(m, out);
            break;
        }
        case StmtKind::Block:
            collectStrings(static_cast<BlockStmt*>(stmt.get())->body, out);
            break;
        case StmtKind::Let:
            collectStringsFromExpr(static_cast<LetStmt*>(stmt.get())->init, out);
            break;
        case StmtKind::Mut:
            collectStringsFromExpr(static_cast<MutStmt*>(stmt.get())->init, out);
            break;
        case StmtKind::Const:
            collectStringsFromExpr(static_cast<ConstStmt*>(stmt.get())->init, out);
            break;
        case StmtKind::Assign: {
            auto* s = static_cast<AssignStmt*>(stmt.get());
            collectStringsFromExpr(s->target, out);
            collectStringsFromExpr(s->value, out);
            break;
        }
        case StmtKind::Return: {
            auto* s = static_cast<ReturnStmt*>(stmt.get());
            if (s->expr.has_value()) collectStringsFromExpr(s->expr.value(), out);
            break;
        }
        case StmtKind::If: {
            auto* s = static_cast<IfStmt*>(stmt.get());
            collectStringsFromExpr(s->cond, out);
            collectStringsFromStmt(s->thenBranch, out);
            collectStringsFromStmt(s->elseBranch, out);
            break;
        }
        case StmtKind::For: {
            auto* s = static_cast<ForStmt*>(stmt.get());
            collectStringsFromExpr(s->iterable, out);
            collectStringsFromStmt(s->body, out);
            break;
        }
        case StmtKind::While: {
            auto* s = static_cast<WhileStmt*>(stmt.get());
            collectStringsFromExpr(s->cond, out);
            collectStringsFromStmt(s->body, out);
            break;
        }
        case StmtKind::Match: {
            auto* s = static_cast<MatchExpr*>(stmt.get());
            collectStringsFromExpr(s->scrutinee, out);
            for (const auto& arm : s->arms) {
                collectStringsFromExpr(arm.pattern, out);
                collectStringsFromStmt(arm.body, out);
            }
            break;
        }
        case StmtKind::Expr:
        case StmtKind::Expression:
            collectStringsFromExpr(static_cast<ExprStmt*>(stmt.get())->expr, out);
            break;
        default:
            break;
    }
}

void LLVMIRGenerator::collectStringsFromExpr(const ExprPtr& expr, std::vector<std::string>& out) {
    if (!expr) return;
    switch (expr->kind()) {
        case ExprKind::Literal: {
            auto* lit = static_cast<LiteralExpr*>(expr.get());
            if (lit->val.kind == ClassifyResult::String &&
                std::find(out.begin(), out.end(), lit->val.strVal) == out.end())
                out.push_back(lit->val.strVal);
            break;
        }
        case ExprKind::BinaryOp: {
            auto* op = static_cast<BinaryOpExpr*>(expr.get());
            collectStringsFromExpr(op->left, out);
            collectStringsFromExpr(op->right, out);
            break;
        }
        case ExprKind::UnaryOp:
            collectStringsFromExpr(static_cast<UnaryOpExpr*>(expr.get())->operand, out);
            break;
        case ExprKind::Call: {
            auto* call = static_cast<CallExpr*>(expr.get());
            collectStringsFromExpr(call->callee, out);
            for (const auto& arg : call->args) collectStringsFromExpr(arg, out);
            break;
        }
        case ExprKind::FieldAccess:
            collectStringsFromExpr(static_cast<FieldAccessExpr*>(expr.get())->obj, out);
            break;
        case ExprKind::StructLit: {
            auto* sl = static_cast<StructLitExpr*>(expr.get());
            for (const auto& [fname, fexpr] : sl->fields) {
                (void)fname;
                collectStringsFromExpr(fexpr, out);
            }
            break;
        }
        case ExprKind::Range: {
            auto* r = static_cast<RangeExpr*>(expr.get());
            collectStringsFromExpr(r->start, out);
            collectStringsFromExpr(r->end, out);
            break;
        }
        case ExprKind::TypeCast:
            collectStringsFromExpr(static_cast<TypeCastExpr*>(expr.get())->expr, out);
            break;
        case ExprKind::Conditional: {
            auto* ce = static_cast<ConditionalExpr*>(expr.get());
            collectStringsFromExpr(ce->cond, out);
            collectStringsFromExpr(ce->thenValue, out);
            collectStringsFromExpr(ce->elseValue, out);
            break;
        }
        case ExprKind::StringInterp: {
            auto* si = static_cast<StringInterpExpr*>(expr.get());
            for (const auto& p : si->parts) collectStringsFromExpr(p, out);
            break;
        }
        default:
            break;
    }
}

// ---- scopes ----

void LLVMIRGenerator::pushScope() {
    scopeStack_.push_back(slots_);
}

void LLVMIRGenerator::popScope() {
    if (!scopeStack_.empty()) {
        slots_ = scopeStack_.back();
        scopeStack_.pop_back();
    }
}

// ---- globals ----

void LLVMIRGenerator::declareGlobals(const Program& prog) {
    for (const auto& item : prog.topLevel) {
        if (!item) continue;
        std::string name;
        TypePtr declared;
        ExprPtr init;
        switch (item->kind()) {
            case StmtKind::Let: {
                auto* s = static_cast<LetStmt*>(item.get());
                name = s->name; declared = s->type; init = s->init;
                break;
            }
            case StmtKind::Mut: {
                auto* s = static_cast<MutStmt*>(item.get());
                name = s->name; declared = s->type; init = s->init;
                break;
            }
            case StmtKind::Const: {
                auto* s = static_cast<ConstStmt*>(item.get());
                name = s->name; init = s->init;
                break;
            }
            default:
                continue;
        }
        TypePtr eff = declared ? declared : inferTypeOf(init.get());
        if (!eff) eff = std::make_shared<BasicType>("int");

        GlobalVar g;
        g.name = name;
        g.gvName = "gv." + sanitize(name);
        g.llvmTy = getTypeStr(eff);
        if (g.llvmTy == "void") g.llvmTy = "i32";
        g.vt = vtOfType(eff);
        g.typeName = eff->getName();
        g.init = init;

        // Redefinition: keep the first cell, re-point to it (last init wins in main)
        bool replaced = false;
        for (auto& prev : globals_) {
            if (prev.name == name) { prev.init = init; replaced = true; break; }
        }
        if (!replaced) globals_.push_back(g);
    }

    // Zero-initialized cells; main() stores the real initializers at startup.
    for (const auto& g : globals_) {
        irStream_ << "@" << g.gvName << " = internal global "
                  << g.llvmTy << " zeroinitializer\n";
    }
    if (!globals_.empty()) irStream_ << "\n";
}

void LLVMIRGenerator::injectGlobalSlots() {
    for (const auto& g : globals_) {
        if (slots_.count(g.name)) continue; // params/locals shadow the global
        Slot s;
        s.reg = "@" + g.gvName;
        s.llvmTy = g.llvmTy;
        s.vt = g.vt;
        s.typeName = g.typeName;
        slots_[g.name] = s;
    }
}

bool LLVMIRGenerator::emitGlobalInits() {
    if (globals_.empty()) return false;
    for (const auto& g : globals_) {
        Val v;
        if (g.init) {
            v = emitExpr(g.init);
        } else if (g.vt == VT::Float) {
            v = Val{"0.0", VT::Float, ""};
        } else if (g.vt == VT::Bool) {
            v = Val{"0", VT::Bool, ""};
        } else if (g.vt == VT::Str) {
            v = stringConstant("");
        } else {
            v = makeInt(0);
        }
        storeToSlot("@" + g.gvName, g.llvmTy, v);
    }
    return true;
}

// ---- internal helpers ----

TypePtr LLVMIRGenerator::inferTypeOf(const Expr* e) const {
    if (!e) return nullptr;
    switch (e->kind()) {
        case ExprKind::Conditional: {
            auto* ce = static_cast<const ConditionalExpr*>(e);
            TypePtr t = inferTypeOf(ce->thenValue.get());
            return t ? t : inferTypeOf(ce->elseValue.get());
        }
        case ExprKind::StringInterp:
            return std::make_shared<BasicType>("string");
        case ExprKind::Literal: {
            auto* lit = static_cast<const LiteralExpr*>(e);
            switch (lit->val.kind) {
                case ClassifyResult::Integer: return std::make_shared<BasicType>("int");
                case ClassifyResult::Float: return std::make_shared<BasicType>("float64");
                case ClassifyResult::Bool: return std::make_shared<BasicType>("bool");
                case ClassifyResult::String: return std::make_shared<BasicType>("string");
                case ClassifyResult::Char: return std::make_shared<BasicType>("char");
                default: return nullptr;
            }
        }
        case ExprKind::Ident: {
            auto* id = static_cast<const IdentExpr*>(e);
            auto it = slots_.find(id->name);
            if (it != slots_.end() && !it->second.typeName.empty())
                return std::make_shared<BasicType>(it->second.typeName);
            return nullptr;
        }
        case ExprKind::BinaryOp: {
            auto* op = static_cast<const BinaryOpExpr*>(e);
            TypePtr lt = inferTypeOf(op->left.get());
            if (lt && lt->getName() == "string") return lt;
            return inferTypeOf(op->right.get()) ? inferTypeOf(op->right.get()) : lt;
        }
        case ExprKind::UnaryOp:
            return inferTypeOf(static_cast<const UnaryOpExpr*>(e)->operand.get());
        case ExprKind::Call: {
            auto* call = static_cast<const CallExpr*>(e);
            auto* id = dynamic_cast<const IdentExpr*>(call->callee.get());
            if (id) {
                // Builtin return types (no FunctionDecl exists for them)
                static const std::map<std::string, std::string> builtinRet = {
                    {"int", "int"}, {"float", "float64"},
                    {"str", "string"}, {"input", "string"},
                    {"upper", "string"}, {"lower", "string"}, {"chr", "string"},
                    {"sqrt", "float64"}, {"pow", "float64"},
                    {"floor", "float64"}, {"ceil", "float64"},
                    {"abs", "int"}, {"min", "int"}, {"max", "int"},
                    {"len", "int"}, {"ord", "int"},
                    {"contains", "bool"},
                    {"read_file", "string"}, {"substring", "string"},
                    {"repeat", "string"},
                    {"write_file", "bool"}, {"append_file", "bool"},
                    {"file_exists", "bool"}, {"delete_file", "bool"},
                    // OS builtins
                    {"run_command", "int"}, {"exec_output", "string"},
                     {"open_app", "bool"},
                     // serial (hardware chat)
                     {"serial_open", "bool"}, {"serial_write", "bool"},
                     {"serial_read_line", "string"}, {"serial_close", "int"},
                     // OS helpers
                     {"sleep", "void"}, {"env_get", "string"},
                     {"cwd", "string"}, {"path_join", "string"},
                 };
                auto bit = builtinRet.find(id->name);
                if (bit != builtinRet.end())
                    return std::make_shared<BasicType>(bit->second);
                // abs/min/max keep the operand's numeric type
                if (id->name == "abs" || id->name == "min" || id->name == "max") {
                    TypePtr at = call->args.empty() ? nullptr
                                                    : inferTypeOf(call->args[0].get());
                    if (at && vtOfType(at) == VT::Float)
                        return std::make_shared<BasicType>("float64");
                    return std::make_shared<BasicType>("int");
                }
                auto fit = functions_.find(id->name);
                if (fit != functions_.end() && fit->second->returnType)
                    return fit->second->returnType;
            }
            return nullptr;
        }
        case ExprKind::StructLit:
            return std::make_shared<BasicType>(
                static_cast<const StructLitExpr*>(e)->structName);
        case ExprKind::ArrayLit:
            return std::make_shared<BasicType>("array");
        default:
            return nullptr;
    }
}

Val LLVMIRGenerator::emitAddrOf(const ExprPtr& expr) {
    if (!expr) {
        error("Invalid assignment target");
        return makeInt(0);
    }
    if (auto* id = dynamic_cast<IdentExpr*>(expr.get())) {
        auto it = slots_.find(id->name);
        if (it == slots_.end()) {
            error("Undefined variable: " + id->name, id->line, id->col);
            return makeInt(0);
        }
        const Slot& s = it->second;
        if (s.vt == VT::StructPtr || s.vt == VT::ArrayPtr) {
            // The slot cell stores a *pointer* to the struct/array; dereference it
            // to obtain the actual element address before any field GEP.
            std::string r = newReg();
            irStream_ << "  " << r << " = load ptr, ptr " << s.reg << "\n";
            return Val{r, s.vt, s.typeName};
        }
        return Val{s.reg, s.vt, s.typeName};
    }
    if (auto* ix = dynamic_cast<IndexExpr*>(expr.get())) {
        // lvalue index: arrays = 8 + idx*8 (header skip); strings byte-wise.
        Val base = emitExpr(ix->base);
        Val idx = materialize(emitExpr(ix->index), "i64");
        std::string byteOff;
        if (base.type == VT::Str) {
            byteOff = idx.ref;
        } else {
            std::string scaled = newReg();
            irStream_ << "  " << scaled << " = mul i64 " << idx.ref << ", 8\n";
            byteOff = newReg();
            irStream_ << "  " << byteOff << " = add i64 " << scaled
                      << ", 8\n";
        }
        std::string slot = newReg();
        irStream_ << "  " << slot << " = getelementptr inbounds i8, ptr "
                  << base.ref << ", i64 " << byteOff << "\n";
        return Val{slot, VT::Int, ""};
    }
    if (auto* fa = dynamic_cast<FieldAccessExpr*>(expr.get())) {
        Val base = emitAddrOf(fa->obj);
        if (base.typeName.empty() || !structs_.count(base.typeName)) {
            error("Field access on non-struct value", fa->line, fa->col);
            return makeInt(0);
        }
        const std::string key = base.typeName + "." + fa->field;
        if (!fieldIndex_.count(key)) {
            error("Unknown field: " + key, fa->line, fa->col);
            return makeInt(0);
        }
        std::string fieldType = "int";
        for (const auto& [fn, ft] : structs_[base.typeName]) {
            if (fn == fa->field && ft) { fieldType = ft->getName(); break; }
        }
        std::string gep = newReg();
        irStream_ << "  " << gep << " = getelementptr inbounds "
                  << llvmTypeName(base.typeName) << ", ptr " << base.ref
                  << ", i32 0, i32 " << fieldIndex_[key] << "\n";
        return Val{gep, vtOfType(std::make_shared<BasicType>(fieldType)), fieldType};
    }
    error("Invalid assignment target", expr->line, expr->col);
    return makeInt(0);
}

bool LLVMIRGenerator::terminated() const {
    return lastIsTerminator(irStream_);
}

void LLVMIRGenerator::error(const std::string& msg, int line, int col) {
    diag_.error("CG002", msg, line, col);
    hasError_ = true;
}

std::string LLVMIRGenerator::label(const std::string& base) {
    static int counter = 0;
    return base + "." + std::to_string(counter++);
}

bool LLVMIRGenerator::compile(const Program& prog, const std::string& outputPath, const std::string& clangPath) {
    std::string ir = generate(prog);
    if (hasError_) return false;

    std::string irPath = outputPath + ".ll";
    {
        std::ofstream irFile(irPath);
        if (!irFile) {
            error("Cannot write IR file: " + irPath);
            return false;
        }
        irFile << ir;
    }

#ifdef _WIN32
    const char pathSep = ';';
    const std::string clangName = "clang.exe";
    const std::string exeSuffix = ".exe";
#else
    const char pathSep = ':';
    const std::string clangName = "clang";
    const std::string exeSuffix = "";
#endif

    auto findTool = [&](const std::string& name) -> std::string {
        // 1) Explicit override wins (set per machine, e.g. EC_CLANG=/path/to/clang)
        if (name == clangName) {
            const char* envClang = std::getenv("EC_CLANG");
            if (envClang && fs::exists(envClang)) return envClang;
        }
        // 2) Search PATH
        const char* envPath = std::getenv("PATH");
        if (envPath) {
            std::istringstream iss(envPath);
            std::string dir;
            while (std::getline(iss, dir, pathSep)) {
                if (dir.empty()) continue;
                std::string candidate = dir + "/" + name;
                if (fs::exists(candidate)) return candidate;
            }
        }
        // 3) Fallback absolute locations — compilers must work even when the
        //    user's terminal PATH is minimal (e.g. VSCode integrated terminal).
        std::string localBin;
        if (const char* home = std::getenv("HOME"))
            localBin = std::string(home) + "/.local/bin";
        std::vector<std::string> extraDirs = {
            "/tmp/opencode/bin",          // dev toolchain on this machine
            localBin,                     // persistent user installs (~/.local/bin)
            "/usr/local/bin", "/usr/bin",
            "/opt/homebrew/bin",          // macOS arm64
            "/usr/lib/llvm-18/bin", "/usr/lib/llvm-17/bin",
            "/usr/lib/llvm-16/bin", "/usr/lib/llvm-15/bin",
            "/usr/lib/llvm-14/bin",
        };
        for (const auto& d : extraDirs) {
            if (d.empty()) continue;
            std::string candidate = d + "/" + name;
            if (fs::exists(candidate)) return candidate;
        }
        // 4) Versioned clang binaries (clang-18 … clang-14)
        if (name == clangName) {
            for (int v = 18; v >= 14; --v) {
                std::string candidate =
                    std::string("/usr/bin/clang-") + std::to_string(v);
                if (fs::exists(candidate)) return candidate;
            }
        }
        return "";
    };

    bool ok = false;
    std::string outPath = outputPath + exeSuffix;
    bool viaZig = false;
    std::string cl = clangPath;
    if (cl.empty()) cl = findTool(clangName);
    if (cl.empty() && !findTool("llvm-as").empty() && !findTool("llc").empty()) {
        // keep llvm-as+llc+cc fallback available below
    } else if (cl.empty()) {
        // Zig bundles clang — `zig cc` compiles LLVM IR like clang does.
        std::string zig = findTool("zig");
        if (!zig.empty()) {
            cl = zig;
            viaZig = true;
        }
    }
    if (!cl.empty()) {
        std::string cmd = cl + (viaZig ? " cc" : "") + " -O2 \"" + irPath +
                          "\" -o \"" + outPath + "\"";
#ifndef _WIN32
        cmd += " -lm"; // libm: sqrt/pow/floor/ceil
#endif
        ok = std::system(cmd.c_str()) == 0;
        if (!ok) error(viaZig ? "Failed to compile LLVM IR with zig cc"
                              : "Failed to compile LLVM IR with clang");
    } else {
        // Fallback toolchain: llvm-as → llc → cc (no clang required)
        std::string as = findTool("llvm-as");
        std::string llc = findTool("llc");
        std::string cc = findTool("cc");
        if (cc.empty()) cc = findTool("gcc");
        if (as.empty() || llc.empty() || cc.empty()) {
            error("No suitable backend found: install clang (or zig), "
                  "or llvm-as+llc+cc in PATH. EC_CLANG env can point to clang.");
            return false;
        }
        std::string bcPath = outputPath + ".bc";
        std::string objPath = outputPath + ".o";
        std::string linkExtra;
#ifndef _WIN32
        linkExtra = " -lm";
#endif
        ok = std::system((as + " \"" + irPath + "\" -o \"" + bcPath + "\"").c_str()) == 0 &&
             std::system((llc + " -filetype=obj -relocation-model=pic \"" + bcPath +
                          "\" -o \"" + objPath + "\"").c_str()) == 0 &&
             std::system((cc + " \"" + objPath + "\" -o \"" + outPath + "\"" + linkExtra).c_str()) == 0;
        fs::remove(bcPath);
        fs::remove(objPath);
        if (!ok) error("Failed to compile LLVM IR with llvm-as/llc/cc fallback");
    }
    if (ok) {
        if (!std::getenv("EC_KEEP_IR")) fs::remove(irPath); // EC_KEEP_IR=1 keeps it
    }
    return ok;
}

