// LLVM type text for an expression value type
const char* vtLLVM(VT t) {
    switch (t) {
        case VT::Float: return "double";
        case VT::Bool: return "i1";
        case VT::Str:
        case VT::StructPtr:
        case VT::ArrayPtr: return "ptr";
        default: return "i32";
    }
}

std::string fmtDouble(double d) {
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.17g", d);
    std::string s = buf;
    if (s.find('.') == std::string::npos && s.find('e') == std::string::npos &&
        s.find('n') == std::string::npos && s.find('i') == std::string::npos) {
        s += ".0";
    }
    return s;
}

std::string sanitize(const std::string& name) {
    std::string out = name;
    for (char& c : out) {
        if (!std::isalnum(static_cast<unsigned char>(c))) c = '_';
    }
    return out;
}

bool lastIsTerminator(const std::stringstream& ss) {
    auto v = ss.view();
    size_t end = v.size();
    while (end > 0 && std::isspace(static_cast<unsigned char>(v[end - 1]))) --end;
    size_t start = v.rfind('\n', end ? end - 1 : 0);
    start = start == std::string_view::npos ? 0 : start + 1;
    std::string_view line = v.substr(start, end - start);
    while (!line.empty() && std::isspace(static_cast<unsigned char>(line.front()))) {
        line.remove_prefix(1);
    }
    return line.rfind("ret ", 0) == 0 || line.rfind("br ", 0) == 0 ||
           line.rfind("switch ", 0) == 0 || line == "unreachable";
}

