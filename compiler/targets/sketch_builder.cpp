// EnginotechC++ — Arduino Sketch Builder Implementation (revised)
// Assembles the top-level structure of an Arduino .ino sketch.
//
// Architecture (one file per responsibility):
//   shim.h / shim.cpp      — runtime bridge to Arduino APIs
//   expr_emitter.h/.cpp    — expression → Arduino C++ text
//   stmt_emitter.h/.cpp    — statement → Arduino C++ text
//   sketch_builder.h/.cpp  — orchestrate full .ino output

