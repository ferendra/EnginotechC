static const uint8_t* glyphFor(char ch) {
    unsigned char u = static_cast<unsigned char>(ch);
    if (u < 32 || u > 126) return kFont5x7[0];
    return kFont5x7[u - 32];
}

static const uint8_t* glyphBoldFor(char ch) {
    unsigned char u = static_cast<unsigned char>(ch);
    if (u < 32 || u > 126) return kFontBold5x7[0];
    return kFontBold5x7[u - 32];
}

int Surface::drawChar(int x, int y, char ch, Color c, int scale) {
    const uint8_t* g = glyphFor(ch);
    for (int col = 0; col < 5; ++col) {
        uint8_t bits = g[col];
        for (int row = 0; row < 7; ++row) {
            if (bits & (1u << row)) {
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        setPixel(x + col * scale + sx, y + row * scale + sy, c);
            }
        }
    }
    return 6 * scale;
}

int Surface::drawCharBold(int x, int y, char ch, Color c, int scale) {
    const uint8_t* g = glyphBoldFor(ch);
    for (int col = 0; col < 5; ++col) {
        uint8_t bits = g[col];
        for (int row = 0; row < 7; ++row) {
            if (bits & (1u << row)) {
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        setPixel(x + col * scale + sx, y + row * scale + sy, c);
            }
        }
    }
    return 6 * scale;
}

int Surface::drawTextConfigured(int x, int y, const std::string& s, Color c, const FontConfig& font) {
    int cx = x;
    for (char ch : s) {
        cx += drawChar(cx, y, ch, c, font.size / 7 + 1);
        cx += font.letterSpacing;
    }
    return cx - x;
}

int Surface::drawTextConfiguredBold(int x, int y, const std::string& s, Color c, const FontConfig& font) {
    int cx = x;
    for (char ch : s) {
        cx += drawCharBold(cx, y, ch, c, font.size / 7 + 1);
        cx += font.letterSpacing;
    }
    return cx - x;
}

int Surface::textWidth(const std::string& s, int scale) const {
    return s.empty() ? 0 : static_cast<int>(s.size()) * 6 * scale - scale;
}

void Surface::drawText(int x, int y, const std::string& s, Color c, int scale) {
    int cx = x;
    for (char ch : s) cx += drawChar(cx, y, ch, c, scale);
}

bool Surface::savePPM(const std::string& path) const {
    std::ofstream f(path, std::ios::binary);
    if (!f) return false;
    f << "P6\n" << w_ << " " << h_ << "\n255\n";
    for (int y = 0; y < h_; ++y)
        for (int x = 0; x < w_; ++x) {
            const uint32_t p = at(x, y);
            f.put(char((p >> 16) & 0xFF));
            f.put(char((p >> 8) & 0xFF));
            f.put(char(p & 0xFF));
        }
    return bool(f);
}

