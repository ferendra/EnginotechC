void Surface::resize(int w, int h) {
    w_ = w > 0 ? w : 1;
    h_ = h > 0 ? h : 1;
    px_.assign(static_cast<size_t>(w_) * h_, 0xFF000000u);
}

void Surface::setPixel(int x, int y, Color c) {
    if (x < 0 || y < 0 || x >= w_ || y >= h_) return;
    at(x, y) = (uint32_t(c.a) << 24) | (uint32_t(c.r) << 16) |
               (uint32_t(c.g) << 8) | c.b;
}

void Surface::clear(Color c) {
    uint32_t v = (uint32_t(c.a) << 24) | (uint32_t(c.r) << 16) |
                 (uint32_t(c.g) << 8) | c.b;
    std::fill(px_.begin(), px_.end(), v);
}

void Surface::fillRect(int x, int y, int w, int h, Color c) {
    int x1 = x + w, y1 = y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (x1 > w_) x1 = w_;
    if (y1 > h_) y1 = h_;
    for (int yy = y; yy < y1; ++yy)
        for (int xx = x; xx < x1; ++xx)
            setPixel(xx, yy, c);
}

void Surface::drawHLine(int x, int y, int w, Color c) { fillRect(x, y, w, 1, c); }
void Surface::drawVLine(int x, int y, int h, Color c) { fillRect(x, y, 1, h, c); }

void Surface::drawRect(int x, int y, int w, int h, Color c) {
    drawHLine(x, y, w, c);
    drawHLine(x, y + h - 1, w, c);
    drawVLine(x, y, h, c);
    drawVLine(x + w - 1, y, h, c);
}

void Surface::drawLine(int x0, int y0, int x1, int y1, Color c) {
    int dx = std::abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -std::abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    while (true) {
        setPixel(x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void Surface::fillCircle(int cx, int cy, int radius, Color c) {
    for (int dy = -radius; dy <= radius; ++dy)
        for (int dx = -radius; dx <= radius; ++dx)
            if (dx * dx + dy * dy <= radius * radius)
                setPixel(cx + dx, cy + dy, c);
}

void Surface::fillGradientRect(int x, int y, int w, int h, Color top, Color bottom, bool vertical) {
    if (vertical) {
        for (int yy = y; yy < y + h; ++yy) {
            double t = (yy - y) / (double)h;
            uint8_t r = (uint8_t)(top.r + (bottom.r - top.r) * t);
            uint8_t g = (uint8_t)(top.g + (bottom.g - top.g) * t);
            uint8_t b = (uint8_t)(top.b + (bottom.b - top.b) * t);
            Color c{r, g, b};
            for (int xx = x; xx < x + w; ++xx) setPixel(xx, yy, c);
        }
    } else {
        for (int xx = x; xx < x + w; ++xx) {
            double t = (xx - x) / (double)w;
            uint8_t r = (uint8_t)(top.r + (bottom.r - top.r) * t);
            uint8_t g = (uint8_t)(top.g + (bottom.g - top.g) * t);
            uint8_t b = (uint8_t)(top.b + (bottom.b - top.b) * t);
            Color c{r, g, b};
            for (int yy = y; yy < y + h; ++yy) setPixel(xx, yy, c);
        }
    }
}

void Surface::fillHGradientRect(int x, int y, int w, int h, Color left, Color right) {
    fillGradientRect(x, y, w, h, left, right, false);
}

void Surface::fillRoundedRect(int x, int y, int w, int h, Color c, int radius) {
    radius = std::min(radius, std::min(w / 2, h / 2));
    // Center fill
    if (w > 2 * radius && h > 2 * radius)
        fillRect(x + radius, y + radius, w - 2 * radius, h - 2 * radius, c);
    // Corner circles
    fillCircle(x + radius, y + radius, radius, c);
    fillCircle(x + w - radius - 1, y + radius, radius, c);
    fillCircle(x + radius, y + h - radius - 1, radius, c);
    fillCircle(x + w - radius - 1, y + h - radius - 1, radius, c);
    // Edge fills
    if (h > 2 * radius) fillRect(x, y + radius, w, h - 2 * radius, c);
    if (w > 2 * radius) fillRect(x + radius, y, w - 2 * radius, h, c);
}

